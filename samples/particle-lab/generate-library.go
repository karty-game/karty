//go:build ignore

// Compose the reusable library from retained recipes and authored effect fragments.
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/karty-game/karty-sdk/format/worldsource"
	"github.com/karty-game/karty/internal/sampleformat"
	"go.yaml.in/yaml/v3"
)

const effectsRoot = "samples/particle-lab/effects"

func main() {
	check := flag.Bool("check", false, "verify composed library without writing")
	flag.Parse()
	if err := compose(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func read(name string) (*yaml.Node, error) {
	data, err := os.ReadFile(filepath.Join(effectsRoot, name))
	if err != nil {
		return nil, err
	}
	var node yaml.Node
	if err := yaml.Unmarshal(data, &node); err != nil {
		return nil, err
	}
	return node.Content[0], nil
}

func field(node *yaml.Node, name string) *yaml.Node {
	for i := 0; i < len(node.Content); i += 2 {
		if node.Content[i].Value == name {
			return node.Content[i+1]
		}
	}
	return nil
}

func compose(check bool) error {
	base, err := read("library.base.yaml")
	if err != nil {
		return err
	}
	presets := field(field(base, "particles"), "presets")
	prefabs := field(base, "prefabs")
	replacements := map[string]*yaml.Node{}
	var replacementOrder []string
	var newPresets []*yaml.Node
	for _, name := range []string{"acid.yaml", "electric-sparkles.yaml", "electric-discharge.yaml", "explosion.yaml"} {
		fragment, err := read(name)
		if err != nil {
			return err
		}
		if field(fragment, "version").Value != "11" || field(field(fragment, "particles"), "version").Value != "2" {
			return fmt.Errorf("%s requires source 11 / particles 2", name)
		}
		for _, prefab := range field(fragment, "prefabs").Content {
			id := field(prefab, "id").Value
			if replacements[id] != nil {
				return fmt.Errorf("duplicate replacement %s", id)
			}
			replacements[id] = prefab
			replacementOrder = append(replacementOrder, id)
		}
		newPresets = append(newPresets, field(field(fragment, "particles"), "presets").Content...)
	}
	obsolete := map[string]bool{}
	for i, prefab := range prefabs.Content {
		id := field(prefab, "id").Value
		if replacement := replacements[id]; replacement != nil {
			for _, emitter := range field(prefab, "particle_emitters").Content {
				obsolete[field(emitter, "preset").Value] = true
			}
			prefabs.Content[i] = replacement
			delete(replacements, id)
		}
	}
	for _, id := range replacementOrder {
		if replacement := replacements[id]; replacement != nil {
			prefabs.Content = append(prefabs.Content, replacement)
		}
	}
	retained := make([]*yaml.Node, 0, len(presets.Content)+len(newPresets))
	for _, preset := range presets.Content {
		if !obsolete[field(preset, "name").Value] {
			retained = append(retained, preset)
		}
	}
	presets.Content = append(retained, newPresets...)
	approved, err := approvedFire()
	if err != nil {
		return err
	}
	presets.Content = append(presets.Content, field(field(approved, "particles"), "presets").Content...)
	prefabs.Content = append(prefabs.Content, field(approved, "prefabs").Content...)
	var output bytes.Buffer
	output.WriteString("# Generated by generate-library.go from library.base.yaml, authored fragments and the retained Brackeys fire.\n")
	encoder := yaml.NewEncoder(&output)
	encoder.SetIndent(2)
	if err := encoder.Encode(base); err != nil {
		return err
	}
	if err := encoder.Close(); err != nil {
		return err
	}
	path := filepath.Join(effectsRoot, "library.yaml")
	formatted, err := sampleformat.YAML(context.Background(), output.Bytes())
	if err != nil {
		return err
	}

	if check {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(data, formatted) {
			return fmt.Errorf("%s is stale; regenerate particle lab", path)
		}
	} else if err := os.WriteFile(path, formatted, 0644); err != nil {
		return err
	}
	fmt.Printf(
		"Reusable collection: %d presets, %d prefabs (%s).\n",
		len(presets.Content),
		len(prefabs.Content),
		map[bool]string{true: "checked", false: "composed"}[check],
	)
	return nil
}

// Own the fire adaptation once so Hangar and the review room use identical recipes.
func approvedFire() (*yaml.Node, error) {
	imported, err := read("brackeys-fire-combined.yaml")
	if err != nil {
		return nil, err
	}
	var fire worldsource.Document
	if err := imported.Decode(&fire); err != nil {
		return nil, err
	}
	refinement, err := read("fire-refinement.yaml")
	if err != nil {
		return nil, err
	}
	var tongues worldsource.Document
	if err := refinement.Decode(&tongues); err != nil {
		return nil, err
	}
	if fire.Particles == nil || len(fire.Prefabs) != 1 || tongues.Particles == nil || len(tongues.Prefabs) != 1 {
		return nil, fmt.Errorf("approved fire requires one imported prefab and one tongue fragment")
	}
	for index := range fire.Particles.Presets {
		preset := &fire.Particles.Presets[index]
		if preset.Sprite.Blend != "premultiplied" {
			continue
		}
		for k := range preset.ColorOverLife {
			if preset.ColorOverLife[k].Age < .3360861 {
				continue
			}
			for channel := range preset.ColorOverLife[k].RGBA {
				preset.ColorOverLife[k].RGBA[channel] *= .25
			}
		}
	}
	fire.Particles.Presets = append(fire.Particles.Presets, tongues.Particles.Presets...)
	fire.Prefabs[0].ParticleEmitters = append(fire.Prefabs[0].ParticleEmitters, tongues.Prefabs[0].ParticleEmitters...)
	var result yaml.Node
	if err := result.Encode(fire); err != nil {
		return nil, err
	}
	return &result, nil
}
