// Short aliases keep both the authored TOML and the encoded texture-name
// catalog within the SDK's 16 KiB metadata bounds. The same retained PNGs
// supply runtime rendering, source comparisons and art review.
func writeCompactManifest() {
	var walkNames, idleNames, aliases []string
	entries := map[string]record{}
	for pose := range dungeon.WalkTextureCount + dungeon.WalkDirections {
		alias := characterTextureName(pose)
		if pose >= dungeon.WalkTextureCount {
			idleNames = append(idleNames, alias)
		} else {
			walkNames = append(walkNames, alias)
		}
		aliases = append(aliases, alias)
		entries[alias] = record{"name": alias, "source": alias + ".png"}
	}
	for _, name := range []string{"floor", "wall", "runner", "stone", "gold", "wood", "wax"} {
		entries[name] = materialTexture(name)
	}
	for _, name := range []string{"flame-0", "flame-1", "flame-2", "fire-core", "fire-trail-0", "fire-trail-1", "fire-trail-2", "fire-trail-3", "fire-trail-4", "fire-trail-5", "fire-trail-6", "fire-trail-7", "fire-flash", "fire-ember", "fire-smoke-0", "fire-smoke-1", "shadow", "window", "z-column", "z-pew", "z-sarcophagus", "z-saint", "z-votives", "z-books", "z-decal-damp", "z-decal-rubble", "z-decal-blood", "z-decal-seep"} {
		entries[name] = record{"name": name, "source": name + ".png"}
	}
	entries["z-dirt-variation"] = record{"name": "z-dirt-variation", "source": "z-dirt-variation.png", "profile": "environment"}
	names := make([]string, 0, len(entries))
	for name := range entries {
		names = append(names, name)
	}
	sort.Strings(names)
	ids := map[string]int{}
	// Each encoded {id:uint,name:string} object occupies 33+len(name) bytes.
	// Reserve 512 more for the standard level identity and material marker.
	metadataBound := 512
	var manifest strings.Builder
	manifest.WriteString("# Generated by cmd/author.\ntextures=[\n")
	for i, name := range names {
		ids[name] = i + 1
		metadataBound += 33 + len(name)
		manifest.WriteString(inlineTOML(entries[name]))
		manifest.WriteString(",\n")
	}
	manifest.WriteString("]\n[level]\nname='levels.crypt'\nkind='world'\n[world]\nsource='world.yaml'\nmax_sprite_texels_per_unit=0\n")
	if manifest.Len() > 16*1024 || metadataBound > 16*1024 || 3*len(names)+16 > 2048 {
		panic(
			fmt.Sprintf(
				"Vigil exceeds pinned metadata bounds: manifest=%d catalog-bound=%d textures=%d",
				manifest.Len(),
				metadataBound,
				len(names),
			),
		)
	}
	firstWalk, firstIdle := ids[aliases[0]], ids[aliases[dungeon.WalkTextureCount]]
	for i, alias := range aliases {
		if ids[alias] != firstWalk+i {
			panic("whole-body aliases must preserve contiguous phase ordering")
		}
	}
	var generated strings.Builder
	generated.WriteString("// Code generated by cmd/author. DO NOT EDIT.\npackage main\n\nconst (\n")
	fmt.Fprintf(
		&generated,
		"firstWalkPilgrimTexture=%d\nfirstIdlePilgrimTexture=%d\nflameTexture=%d\nshadowTexture=%d\n",
		firstWalk,
		firstIdle,
		ids["flame-0"],
		ids["shadow"],
	)
	fmt.Fprintf(
		&generated,
		"fireCoreTexture=%d\nfireTrailTexture=%d\nfireFlashTexture=%d\nfireEmberTexture=%d\nfireSmokeTexture=%d\n)\n",
		ids["fire-core"],
		ids["fire-trail-0"],
		ids["fire-flash"],
		ids["fire-ember"],
		ids["fire-smoke-0"],
	)
	must(os.WriteFile("src/textures.generated.go", []byte(generated.String()), 0644))
	var rig [dungeon.WalkTextureCount + dungeon.WalkDirections]record
	var compositeNames []string
	for pose, data := range activeRig {
		rig[pose] = record{
			"offsetX": data.OffsetX,
			"offsetY": data.OffsetY,
			"offsetZ": data.OffsetZ,
			"originX": data.OriginX,
			"originY": data.OriginY,
		}
		compositeNames = append(compositeNames, characterTextureName(pose))
	}
	writeWalkRig()
	metadata, err := json.MarshalIndent(record{
		"version":          3,
		"directions":       dungeon.WalkDirections,
		"frames":           dungeon.WalkFrames,
		"stride":           dungeon.WalkStride,
		"moveSpeed":        dungeon.MoveSpeed,
		"hastenSpeed":      dungeon.HastenSpeed,
		"firstWalkTexture": firstWalk,
		"firstIdleTexture": firstIdle,
		"rootTexture":      ids["shadow"],
		"walkNames":        walkNames,
		"idleNames":        idleNames,
		"textureDirectory": "levels/crypt",
		"aliases":          aliases,
		"projectedSize":    rigProjectedSize,
		"originX":          rigRootX / float64(rigCanvas),
		"originY":          rigRootY / float64(rigCanvas),
		"canvasSize":       rigCanvas,
		"rig":              rig,
		"compositeNames":   compositeNames,
		"fireTextures": record{
			"first": ids["fire-core"],
			"last":  ids["fire-trail-7"],
			"core":  ids["fire-core"],
			"flash": ids["fire-flash"],
			"ember": ids["fire-ember"],
			"smoke": ids["fire-smoke-0"],
			"trail": ids["fire-trail-0"],
		},
		"manifestBytes":             manifest.Len(),
		"encodedMetadataUpperBound": metadataBound,
	}, "", "  ")
	must(err)
	// Keep art-validation metadata with its exact frames in project snapshots.
	// It is not referenced by the game or packaged level manifest.
	must(os.WriteFile(filepath.Join(target, "walk.generated.json"), append(metadata, '\n'), 0644))
	must(os.WriteFile(filepath.Join(target, "level.toml"), []byte(manifest.String()), 0644))
	fmt.Printf(
		"Vigil metadata: %d-byte manifest, <=%d-byte encoded catalog, %d packaged textures\n",
		manifest.Len(),
		metadataBound,
		len(names),
	)
}

func inlineTOML(value any) string {
	switch value := value.(type) {
	case string:
		return strconv.Quote(value)
	case int:
		return strconv.Itoa(value)
	case float64:
		text := strconv.FormatFloat(value, 'f', -1, 64)
		if !strings.Contains(text, ".") {
			text += ".0"
		}
		return text
	case record:
		keys := make([]string, 0, len(value))
		for key := range value {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		var fields []string
		for _, key := range keys {
			fields = append(fields, key+"="+inlineTOML(value[key]))
		}
		return "{" + strings.Join(fields, ",") + "}"
	default:
		panic(fmt.Sprintf("unsupported manifest value %T", value))
	}
}

func materialTexture(name string) record {
	result := record{"name": name, "source": name + ".png", "profile": "environment"}
	if name == "wax" {
		return result
	}
	recipe := record{"preset": "stone", "normal_strength": .8, "height_contrast": .5, "metallic_scale": 0.0}
	strengths := record{"normal": .8, "height": .5, "ao": .9, "rim": .15}
	switch name {
	case "floor":
		// The original 1774x887 study is retained in art. Its packaged albedo
		// otherwise consumes 3.3 MiB even though world material tiles are 256px.
		// Bound that duplicate texture while preserving aspect and material art.
		result["transform"] = record{"max_width": 1024, "max_height": 512}
		recipe = record{"preset": "marble", "normal_strength": 2.8, "height_contrast": 2.2, "metallic_scale": 0.0, "ao_depth_scale": 2.5}
		strengths = record{"normal": 1.0, "height": .85, "ao": 1.0, "rim": .2}
	case "gold":
		recipe = record{"preset": "metal", "normal_strength": .4, "height_contrast": .3, "metallic_scale": 1.0}
		strengths = record{"normal": .4, "height": .1, "ao": .8, "rim": .2}
	case "wood":
		recipe = record{"preset": "wood", "metallic_scale": 0.0}
		strengths = record{"normal": .55, "height": .2, "ao": .9, "rim": .1}
	case "runner":
		recipe = record{"preset": "fabric", "metallic_scale": 0.0}
		strengths = record{"normal": .45, "height": .25, "ao": 1.0, "rim": 0.0}
	}
	result["materialize"], result["material_strengths"] = recipe, strengths
	return result
}
