// Export conservative alpha and geometry silhouettes, so the floor mask retains
// visible actors and solid crowns. Source artwork and geometry remain unchanged.
func writeSightArt() {
	var out strings.Builder
	out.WriteString("// Code generated by cmd/author. DO NOT EDIT.\npackage dungeon\n\n")
	fmt.Fprintf(
		&out,
		"const (HeroProjectedSize = %.12g; HeroOriginX = %.12g; HeroOriginY = %.12g)\n\n",
		rigProjectedSize,
		rigRootX/float64(rigCanvas),
		rigRootY/float64(rigCanvas),
	)
	out.WriteString("var artHulls = [...]silhouette{\n")
	ids := map[string]int{}
	emitHull := func(name string, points [][2]float64) int {
		if id, ok := ids[name]; ok {
			return id
		}
		id := len(ids)
		ids[name] = id
		if len(points) > 64 {
			panic("sight silhouette exceeds 64 corners: " + name)
		}
		fmt.Fprintf(&out, "{count:%d,points:[64]Point{", len(points))
		for _, p := range points {
			fmt.Fprintf(&out, "{%.8f,%.8f},", p[0], p[1])
		}
		out.WriteString("}},\n")
		return id
	}
	hull := func(name string) int {
		if id, ok := ids[name]; ok {
			return id
		}
		return emitHull(name, alphaHull(load(filepath.Join(target, name+".png"))))
	}
	var pilgrims [dungeon.WalkTextureCount + dungeon.WalkDirections]int
	for row := range dungeon.WalkDirections {
		for frame := range dungeon.WalkFrames {
			pose := row*dungeon.WalkFrames + frame
			name := characterTextureName(pose)
			pilgrims[pose] = emitHull(name, pilgrimSightHull(pose, name))
		}
	}
	for row := range dungeon.WalkDirections {
		pose := dungeon.WalkTextureCount + row
		name := characterTextureName(pose)
		pilgrims[pose] = emitHull(name, pilgrimSightHull(pose, name))
	}
	var sprites strings.Builder
	sprites.WriteString("var sightSprites = [...]sightSprite{\n")
	count := 0
	for _, content := range contents {
		actor := content["actor"].(record)
		s, ok := actor["sprite"].(record)
		if !ok {
			continue
		}
		height, standing := projectedSightHeight(s)
		if !standing {
			continue
		}
		position := content["position"].(record)
		id := hull(s["texture"].(string))
		fmt.Fprintf(
			&sprites,
			"{position:Point{%v,%v},z:%v,width:%v,height:%v,originX:%v,originY:%v,hull:%d},\n",
			position["x"],
			position["y"],
			position["z"],
			s["width"],
			height,
			s["origin_x"],
			s["origin_y"],
			id,
		)
		count++
	}
	// Real furnishings retain their projected geometry above the floor mask.
	// Grouping each obstacle bounds storage independently of its carved pieces.
	for i, bounds := range dungeon.Obstacles {
		name := fmt.Sprintf("obstacle-%02d", i)
		points := obstacleSightHull(name, bounds, solids)
		if len(points) == 0 {
			continue
		}
		id := emitHull("geometry-"+name, points)
		fmt.Fprintf(&sprites, "{position:Point{%v,%v},width:1,height:1,hull:%d},\n", bounds.X, bounds.Y, id)
		count++
	}
	if count > 128 {
		panic("sight actor storage exceeded")
	}
	fmt.Fprintf(&out, "}\n\nvar pilgrimHulls = [%d]int{", len(pilgrims))
	for _, id := range pilgrims {
		fmt.Fprintf(&out, "%d,", id)
	}
	out.WriteString("}\n\n")
	sprites.WriteString("}\n")
	out.WriteString(sprites.String())
	source, err := format.Source([]byte(out.String()))
	must(err)
	must(os.WriteFile("internal/dungeon/vision_art.generated.go", source, 0644))
}

// The whole-body atlas and visual-card anchors preserve the same root projection.
func pilgrimSightHull(_ int, name string) [][2]float64 {
	return alphaHull(load(filepath.Join(target, name+".png")))
}

func projectedSightHeight(sprite record) (float64, bool) {
	switch sprite["facing"] {
	case "upright":
		return sprite["height"].(float64) * uprightProjectionScale(), true
	case "camera-facing":
		panic("standing Vigil sprites must use upright planes with dimetric height compensation")
	default:
		return 0, false
	}
}

func obstacleSightHull(name string, bounds dungeon.Box, geometry []record) [][2]float64 {
	var points [][2]float64
	for _, solid := range geometry {
		id := solid["id"].(string)
		if id != name && !strings.HasPrefix(id, name+"-") {
			continue
		}
		for _, corner := range solid["footprint"].([]record) {
			x, y := corner["x"].(float64), corner["y"].(float64)
			for _, face := range [...]string{"bottom", "top"} {
				z := sourcePlaneHeight(solid[face].(record), x, y)
				dx, dy := x-bounds.X, y-bounds.Y
				points = append(points, [2]float64{(dx - dy) / math.Sqrt2, -(dx+dy)*.5/math.Sqrt2 - z*math.Sqrt(3)/2})
			}
		}
	}
	if len(points) < 3 {
		return nil
	}
	sort.Slice(points, func(i, j int) bool {
		return points[i][0] < points[j][0] || points[i][0] == points[j][0] && points[i][1] < points[j][1]
	})
	turn := func(a, b, c [2]float64) float64 { return (b[0]-a[0])*(c[1]-a[1]) - (b[1]-a[1])*(c[0]-a[0]) }
	var hull [][2]float64
	for _, point := range points {
		for len(hull) >= 2 && turn(hull[len(hull)-2], hull[len(hull)-1], point) <= 0 {
			hull = hull[:len(hull)-1]
		}
		hull = append(hull, point)
	}
	lower := len(hull)
	for i := len(points) - 2; i >= 0; i-- {
		point := points[i]
		for len(hull) > lower && turn(hull[len(hull)-2], hull[len(hull)-1], point) <= 0 {
			hull = hull[:len(hull)-1]
		}
		hull = append(hull, point)
	}
	return hull[:len(hull)-1]
}

//nolint:errcheck,forcetypeassert // Planes are author-owned records whose mandatory constant is established by box/chamfered.
func sourcePlaneHeight(plane record, worldX, worldY float64) float64 {
	height := plane["c"].(float64)
	if slope, ok := plane["a"].(float64); ok {
		height += slope * worldX
	}

	if slope, ok := plane["b"].(float64); ok {
		height += slope * worldY
	}

	return height
}

func alphaHull(im image.Image) [][2]float64 {
	b := im.Bounds()
	var points [][2]int
	for y := b.Min.Y; y < b.Max.Y; y++ {
		left, right := b.Max.X, b.Min.X-1
		for x := b.Min.X; x < b.Max.X; x++ {
			_, _, _, a := im.At(x, y).RGBA()
			if a >= 0x8000 {
				left = min(left, x)
				right = max(right, x)
			}
		}
		if right >= left {
			points = append(points, [2]int{left, y}, [2]int{left, y + 1}, [2]int{right + 1, y}, [2]int{right + 1, y + 1})
		}
	}
	sort.Slice(points, func(i, j int) bool {
		return points[i][0] < points[j][0] || points[i][0] == points[j][0] && points[i][1] < points[j][1]
	})
	turn := func(a, b, c [2]int) int { return (b[0]-a[0])*(c[1]-a[1]) - (b[1]-a[1])*(c[0]-a[0]) }
	var hull [][2]int
	for _, p := range points {
		for len(hull) >= 2 && turn(hull[len(hull)-2], hull[len(hull)-1], p) <= 0 {
			hull = hull[:len(hull)-1]
		}
		hull = append(hull, p)
	}
	lower := len(hull)
	for i := len(points) - 2; i >= 0; i-- {
		p := points[i]
		for len(hull) > lower && turn(hull[len(hull)-2], hull[len(hull)-1], p) <= 0 {
			hull = hull[:len(hull)-1]
		}
		hull = append(hull, p)
	}
	if len(hull) < 4 {
		panic("empty sight silhouette")
	}
	hull = hull[:len(hull)-1]
	result := make([][2]float64, len(hull))
	for i, p := range hull {
		result[i] = [2]float64{float64(p[0]-b.Min.X) / float64(b.Dx()), float64(p[1]-b.Min.Y) / float64(b.Dy())}
	}
	return result
}
