package main

import (
	"fmt"
	"go/format"
	"os"
	"strings"
)

func writeWalkRig() {
	var out strings.Builder
	out.WriteString("// Code generated by cmd/author. DO NOT EDIT.\npackage main\n\n")
	fmt.Fprintf(
		&out,
		"const (pilgrimProjectedSize = %.12g; pilgrimOriginX = %.12g; pilgrimOriginY = %.12g)\n",
		rigProjectedSize,
		rigRootX/float64(rigCanvas),
		rigRootY/float64(rigCanvas),
	)
	out.WriteString("type pilgrimSpritePose struct { OffsetX, OffsetY, OffsetZ, OriginX, OriginY float32 }\n")
	fmt.Fprintf(&out, "var pilgrimSpriteRig = [%d]pilgrimSpritePose{\n", len(activeRig))
	for _, pose := range activeRig {
		fmt.Fprintf(&out, "{%.12g,%.12g,%.12g,%.12g,%.12g},\n", pose.OffsetX, pose.OffsetY, pose.OffsetZ, pose.OriginX, pose.OriginY)
	}
	out.WriteString("}\n")
	source, err := format.Source([]byte(out.String()))
	must(err)
	must(os.WriteFile("src/walk_rig.generated.go", source, 0644))
}
