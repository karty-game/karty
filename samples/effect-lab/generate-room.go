//go:build ignore

// Run from the CLI root: mise run generate-effect-lab.
// Every texture is procedural, with no external artwork or private inputs.
package main

import (
	"fmt"
	"image"
	"image/color"
	"image/png"
	"math"
	"os"
	"strings"
)

func main() {
	must(os.MkdirAll("levels/room", 0755))
	materials := []struct {
		name, preset string
		base         color.RGBA
		metallic     float64
	}{
		{"floor", "concrete", color.RGBA{115, 125, 139, 255}, 0},
		{"wall", "concrete", color.RGBA{137, 145, 154, 255}, 0},
		{"wood", "wood", color.RGBA{151, 93, 47, 255}, 0},
		{"brick", "brick", color.RGBA{156, 67, 49, 255}, 0},
		{"steel", "metal", color.RGBA{135, 158, 176, 255}, .9},
		{"red", "concrete", color.RGBA{230, 45, 60, 255}, 0},
		{"green", "concrete", color.RGBA{45, 207, 100, 255}, 0},
		{"blue", "concrete", color.RGBA{45, 100, 235, 255}, 0},
		{"gold", "metal", color.RGBA{237, 176, 55, 255}, .8},
		{"white", "concrete", color.RGBA{224, 224, 224, 255}, 0},
		{"checker", "concrete", color.RGBA{255, 255, 255, 255}, 0},
		{"gradient", "concrete", color.RGBA{255, 255, 255, 255}, 0},
		{"swatches", "concrete", color.RGBA{255, 255, 255, 255}, 0},
	}
	var level strings.Builder
	level.WriteString(
		"# Generated by generate-room.go.\n[level]\nname = \"levels.effect-lab\"\nkind = \"world\"\n\n[world]\nsource = \"world.yaml\"\n",
	)
	for _, m := range materials {
		pixels := image.NewRGBA(image.Rect(0, 0, 256, 256))
		for y := 0; y < 256; y++ {
			for x := 0; x < 256; x++ {
				pixels.SetRGBA(x, y, texel(m.name, m.base, x, y))
			}
		}
		file, err := os.Create("levels/room/" + m.name + ".png")
		must(err)
		must(png.Encode(file, pixels))
		must(file.Close())
		fmt.Fprintf(
			&level,
			"\n[[textures]]\nname = %q\nsource = %q\nprofile = \"environment\"\n\n[textures.materialize]\npreset = %q\nmetallic_scale = %g\n",
			m.name,
			m.name+".png",
			m.preset,
			m.metallic,
		)
		normal, height := .25, .008
		switch m.name {
		case "red", "green", "blue", "white", "gradient", "swatches", "checker":
			normal, height = 0, 0
		}
		fmt.Fprintf(&level, "\n[textures.material_strengths]\nnormal = %g\nheight = %g\nao = 0.2\nrim = 0\n", normal, height)
	}

	for _, source := range []struct {
		name  string
		color color.RGBA
	}{
		{"bloom-amber", color.RGBA{255, 105, 26, 255}},
		{"bloom-cyan", color.RGBA{25, 205, 255, 255}},
		{"bloom-magenta", color.RGBA{255, 28, 170, 255}},
		{"bloom-white", color.RGBA{255, 245, 222, 255}},
	} {
		pixels := image.NewRGBA(image.Rect(0, 0, 8, 8))
		for y := 0; y < 8; y++ {
			for x := 0; x < 8; x++ {
				pixels.SetRGBA(x, y, source.color)
			}
		}
		file, err := os.Create("levels/room/" + source.name + ".png")
		must(err)
		must(png.Encode(file, pixels))
		must(file.Close())
		fmt.Fprintf(
			&level,
			"\n[[textures]]\nname = %q\nsource = %q\nprofile = \"environment\"\n[textures.material_strengths]\nnormal = 0\nheight = 0\nao = 0\nrim = 0\n[textures.emission]\nintensity = 1.8\n",
			source.name,
			source.name+".png",
		)
	}
	must(os.WriteFile("levels/room/level.toml", []byte(level.String()), 0644))
	var world strings.Builder
	world.WriteString(`# Generated by generate-room.go.
version: 11
uv: { mode: triplanar, scale: { x: 2, y: 2 } }
lighting:
  version: 1
  actors: true
  ambient: { x: 0.22, y: 0.22, z: 0.22 }
  lights:
    - { id: key-warm, position: { x: -4, y: -3, z: 4.5 }, color: { x: 1, y: 0.68, z: 0.38 }, radius: 12 }
    - { id: fill-cool, position: { x: 4, y: 1, z: 4 }, color: { x: 0.3, y: 0.55, z: 1 }, radius: 12 }
    - { id: rim-pink, position: { x: -5, y: 6, z: 3 }, color: { x: 1, y: 0.18, z: 0.5 }, radius: 8 }
    - { id: depth-cyan, position: { x: 5, y: 13, z: 4 }, color: { x: 0.1, y: 1, z: 0.8 }, radius: 10 }
    - { id: chart-neutral, position: { x: 0, y: 5, z: 4.5 }, color: { x: 0.7, y: 0.7, z: 0.7 }, radius: 8 }
rooms:
  - id: lab
    floor: { c: 0 }
    ceiling: { c: 6 }
    floor_material: floor
    ceiling_material: wall
    boundary:
      - { id: south, start: { x: -9, y: -12 }, end: { x: 9, y: -12 }, material: wall }
      - { id: east, start: { x: 9, y: -12 }, end: { x: 9, y: 20 }, material: wall }
      - { id: north, start: { x: 9, y: 20 }, end: { x: -9, y: 20 }, material: brick }
      - { id: west, start: { x: -9, y: 20 }, end: { x: -9, y: -12 }, material: wall }
solids:
`)
	// Leave a clear central aisle and several depth layers for fog comparisons.
	for i, m := range []string{"red", "green", "blue", "wood", "steel", "gold"} {
		x := -5.0
		if i%2 == 1 {
			x = 5
		}
		y := -3 + float64(i/2)*4
		box(&world, fmt.Sprintf("plinth-%d", i), x, y, 0, 2, 2, .35, "wall", 2, 2)
		if i >= 4 {
			column(&world, m, x, y, .35, .7, 2.1, m)
		} else {
			box(&world, m, x, y, .35, 1.3, 1.3, 1.4, m, 1.3, 1.4)
		}
	}
	box(&world, "grayscale", -1.8, 8, .65, 3.4, .18, 2, "gradient", 3.4, 2)
	box(&world, "color-chart", 1.8, 8, .65, 3.4, .18, 2, "swatches", 3.4, 2)
	box(&world, "edge-pattern", -7, 2, .2, 1, .2, 3, "checker", 1, 3)
	for i := 0; i < 4; i++ {
		column(&world, fmt.Sprintf("depth-%d", i), 3.4, 10+float64(i)*2.6, 0, .4, 2.2, "white")
	}
	box(&world, "brick-block", -5.5, 13, 0, 2.5, 2.5, 2, "brick", 2, 2)
	box(&world, "back-checker", 0, 19.7, .5, 4, .15, 3, "checker", 2, 2)

	// Emissive fixtures in the existing room; no second preview or extra camera.
	for i, fixture := range []struct {
		name string
		x, y float64
	}{
		{"bloom-amber", -2.7, .8}, {"bloom-cyan", 2.7, 2.2},
	} {
		column(&world, fmt.Sprintf("bloom-base-%d", i), fixture.x, fixture.y, 0, .3, .5, "steel")
		column(&world, fmt.Sprintf("bloom-tube-%d", i), fixture.x, fixture.y, .5, .075, 1.65, fixture.name)
		column(&world, fmt.Sprintf("bloom-cap-%d", i), fixture.x, fixture.y, 2.15, .12, .12, "steel")
	}
	box(&world, "bloom-magenta-bar", 0, 7.75, 3.35, 3, .1, .065, "bloom-magenta", 3, .065)
	box(&world, "bloom-white-point", -1.7, 4, 2, .055, .055, .055, "bloom-white", 1, 1)
	must(os.WriteFile("levels/room/world.yaml", []byte(world.String()), 0644))
}

func box(out *strings.Builder, id string, x, y, z, w, d, h float64, material string, u, v float64) {
	fmt.Fprintf(out, `  - id: %s
    footprint: [{ x: %g, y: %g }, { x: %g, y: %g }, { x: %g, y: %g }, { x: %g, y: %g }]
    bottom: { c: %g }
    top: { c: %g }
    side_material: %s
    top_material: %s
    bottom_material: %s
    side_uv: { mode: planar, scale: { x: %g, y: %g }, offset: { x: %g, y: %g } }
    collision: true
`, id, x-w/2, y-d/2, x+w/2, y-d/2, x+w/2, y+d/2, x-w/2, y+d/2, z, z+h, material, material, material, u, v, -(x-w/2)/u, -z/v)
}

func column(out *strings.Builder, id string, x, y, z, r, h float64, material string) {
	fmt.Fprintf(out, "  - id: %s\n    footprint:\n", id)
	for i := 0; i < 12; i++ {
		a := float64(i) * math.Pi / 6
		fmt.Fprintf(out, "      - { x: %.5f, y: %.5f }\n", x+r*math.Cos(a), y+r*math.Sin(a))
	}
	fmt.Fprintf(
		out,
		"    bottom: { c: %g }\n    top: { c: %g }\n    side_material: %s\n    top_material: %s\n    bottom_material: %s\n    collision: true\n",
		z,
		z+h,
		material,
		material,
		material,
	)
}

func texel(name string, base color.RGBA, x, y int) color.RGBA {
	if name == "gradient" {
		v := uint8(x)
		return color.RGBA{v, v, v, 255}
	}
	if name == "swatches" {
		hues := [8]color.RGBA{
			{255, 50, 65, 255},
			{255, 145, 25, 255},
			{245, 220, 50, 255},
			{60, 220, 110, 255},
			{40, 210, 230, 255},
			{60, 105, 240, 255},
			{170, 70, 235, 255},
			{235, 235, 235, 255},
		}
		base = hues[x/32]
		f := .15 + .85*float64(255-y)/255
		return color.RGBA{uint8(float64(base.R) * f), uint8(float64(base.G) * f), uint8(float64(base.B) * f), 255}
	}
	if name == "checker" {
		v := uint8(235)
		if (x/8+y/8)%2 == 0 {
			v = 18
		}
		return color.RGBA{v, v, v, 255}
	}
	n := int((uint32(x*1973+y*9277+911)*1274126177)>>27) - 16
	switch name {
	case "wood":
		n += int(16 * math.Sin(float64(x)*.22+3*math.Sin(float64(y)*.04)))
	case "steel":
		n = n/4 + (y%4)*3
	case "brick":
		if y%64 < 5 || (x+(y/64%2)*64)%128 < 5 {
			return color.RGBA{72, 68, 65, 255}
		}
	case "floor":
		if x%128 < 3 || y%128 < 3 {
			return color.RGBA{48, 54, 64, 255}
		}
	default:
		n /= 5
	}
	return color.RGBA{
		uint8(max(0, min(255, int(base.R)+n))),
		uint8(max(0, min(255, int(base.G)+n))),
		uint8(max(0, min(255, int(base.B)+n))),
		255,
	}
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
