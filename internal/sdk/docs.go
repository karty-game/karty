package sdk

import (
	"context"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/karty-game/karty/internal/contextio"
)

const docsManifest = ".karty-docs.json"

const (
	errInvalidDocsPath staticError = "SDK docs contain an invalid path"
	errDocsNotDir      staticError = "SDK reference is not a directory"
	errDocsManifest    staticError = "SDK reference has an invalid generated manifest"
	errDocsSpecial     staticError = "SDK reference entry is not a regular file"
	errDocsModified    staticError = "SDK reference was modified; move user files outside .karty/docs"
	errDocsFileSet     staticError = "SDK reference file set was modified; move user files outside .karty/docs"
)

type docsState struct {
	Warning    string            `json:"warning"`
	DoNotEdit  string            `json:"doNotEdit"`
	Regenerate string            `json:"regenerate"`
	SDK        string            `json:"sdk"`
	Files      map[string]string `json:"files"`
}

// SyncDocs replaces the project-local reference with the exact set selected by
// the SDK. Existing generated files must still match their recorded hashes.
//

func SyncDocs(projectDirectory string, manifest Manifest) error {
	return SyncDocsContext(context.Background(), projectDirectory, manifest)
}

func SyncDocsContext(ctx context.Context, projectDirectory string, manifest Manifest) error {
	if err := ctx.Err(); err != nil {
		return err
	}

	root := filepath.Join(projectDirectory, ".karty", "docs")

	previous, err := verifyDocs(ctx, root)
	if err != nil {
		return err
	}

	if manifest.Docs.Version == "" {
		return os.RemoveAll(root)
	}

	files, err := resolveDocs(ctx, manifest)
	if err != nil {
		return err
	}

	state := docsState{
		Warning:    "GENERATED BY KARTY. DO NOT EDIT.",
		DoNotEdit:  "MANUAL CHANGES WILL BE REJECTED OR REPLACED.",
		Regenerate: "karty build",
		SDK:        manifest.Version,
		Files:      make(map[string]string, len(files)),
	}
	for name, contents := range files {
		state.Files[name], err = digestContext(ctx, contents)
		if err != nil {
			return err
		}
	}

	// Verification above still rejects modified or unexpected project files.
	// Avoid rewriting an identical reference, including for local SDK candidates
	// that retain a version while their contents change.
	if previous.SDK == state.SDK && previous.Warning == state.Warning &&
		previous.DoNotEdit == state.DoNotEdit && previous.Regenerate == state.Regenerate && maps.Equal(previous.Files, state.Files) {
		return ctx.Err()
	}

	if err := os.MkdirAll(filepath.Dir(root), 0o750); err != nil {
		return err
	}

	stage, err := os.MkdirTemp(filepath.Dir(root), ".docs-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage)

	if err := os.Chmod(stage, 0o750); err != nil {
		return err
	}

	for name, contents := range files {
		path := filepath.Join(stage, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			return fmt.Errorf("create SDK reference directory: %w", err)
		}

		if err := contextio.WriteFile(ctx, path, contents, 0o600); err != nil {
			return fmt.Errorf("write SDK reference %s: %w", name, err)
		}
	}

	encoded, err := json.MarshalIndent(state, "", "  ")
	if err != nil {
		return fmt.Errorf("encode SDK reference manifest: %w", err)
	}

	encoded = append(encoded, '\n')
	if err := contextio.WriteFile(ctx, filepath.Join(stage, docsManifest), encoded, 0o600); err != nil {
		return fmt.Errorf("write SDK reference manifest: %w", err)
	}

	return publishDocs(ctx, stage, root)
}

func resolveDocs(ctx context.Context, manifest Manifest) (map[string][]byte, error) {
	tree, err := ResourcesContext(ctx, manifest)
	if err != nil {
		return nil, err
	}

	prefix := "docs/" + manifest.Docs.Version
	result := make(map[string][]byte)

	err = fs.WalkDir(tree, prefix, func(path string, entry fs.DirEntry, walkErr error) error {
		if err := ctx.Err(); err != nil {
			return err
		}

		if walkErr != nil {
			return walkErr
		}

		if entry.IsDir() {
			return nil
		}

		contents, err := fs.ReadFile(tree, path)
		if err != nil {
			return err
		}

		name := strings.TrimPrefix(path, prefix+"/")
		if name == path || name == "" || !fs.ValidPath(name) {
			return fmt.Errorf("SDK docs %s path %q: %w", manifest.Docs.Version, path, errInvalidDocsPath)
		}

		result[name] = contents

		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("resolve SDK docs %s: %w", manifest.Docs.Version, err)
	}

	if len(result) == 0 {
		return nil, fmt.Errorf("resolve SDK docs %s: %w", manifest.Docs.Version, fs.ErrNotExist)
	}

	return result, nil
}

func verifyDocs(ctx context.Context, root string) (docsState, error) {
	info, err := os.Lstat(root)
	if os.IsNotExist(err) {
		return docsState{}, nil
	}

	if err != nil {
		return docsState{}, fmt.Errorf("inspect SDK reference: %w", err)
	}

	if !info.IsDir() {
		return docsState{}, fmt.Errorf("SDK reference %s: %w", root, errDocsNotDir)
	}

	encoded, err := contextio.ReadFile(ctx, filepath.Join(root, docsManifest))
	if err != nil {
		return docsState{}, fmt.Errorf("SDK reference ownership: %w", err)
	}

	var state docsState
	if err := json.Unmarshal(encoded, &state); err != nil || state.Warning != "GENERATED BY KARTY. DO NOT EDIT." {
		return docsState{}, errDocsManifest
	}

	openedRoot, err := os.OpenRoot(root)
	if err != nil {
		return docsState{}, fmt.Errorf("open SDK reference: %w", err)
	}
	defer openedRoot.Close()

	actual := make([]string, 0, len(state.Files))

	err = filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if err := ctx.Err(); err != nil {
			return err
		}

		if walkErr != nil {
			return walkErr
		}

		if entry.IsDir() {
			return nil
		}

		name, relErr := filepath.Rel(root, path)
		if relErr != nil {
			return relErr
		}

		name = filepath.ToSlash(name)
		if name == docsManifest {
			return nil
		}

		if entry.Type()&os.ModeSymlink != 0 || !entry.Type().IsRegular() {
			return fmt.Errorf("SDK reference %s: %w", name, errDocsSpecial)
		}

		actual = append(actual, name)

		contents, readErr := readOwnedDoc(ctx, openedRoot, name)
		if readErr != nil {
			return readErr
		}

		sum, err := digestContext(ctx, contents)
		if err != nil {
			return err
		}

		if state.Files[name] != sum {
			return fmt.Errorf("SDK reference %s: %w", name, errDocsModified)
		}

		return nil
	})
	if err != nil {
		return docsState{}, err
	}

	expected := make([]string, 0, len(state.Files))
	for name := range state.Files {
		expected = append(expected, name)
	}

	slices.Sort(actual)
	slices.Sort(expected)

	if !slices.Equal(actual, expected) {
		return docsState{}, errDocsFileSet
	}

	return state, nil
}

func digestContext(ctx context.Context, contents []byte) (string, error) {
	sum, err := contextio.Sum256(ctx, contents)

	return hex.EncodeToString(sum[:]), err
}

// Publication keeps the previous generated reference intact if preparation was
// canceled. A failed rollback retains the last good backup for recovery.
func publishDocs(ctx context.Context, stage, root string) error {
	if err := ctx.Err(); err != nil {
		return err
	}

	backup := stage + "-previous"
	hadPrevious := false

	if _, err := os.Lstat(root); err == nil {
		if err := os.Rename(root, backup); err != nil {
			return err
		}

		hadPrevious = true
	} else if !os.IsNotExist(err) {
		return err
	}

	if err := os.Rename(stage, root); err != nil {
		if hadPrevious {
			if restoreErr := os.Rename(backup, root); restoreErr != nil {
				return fmt.Errorf("restore SDK reference from %s: %w", backup, errors.Join(err, restoreErr))
			}
		}

		return err
	}

	return os.RemoveAll(backup)
}

func readOwnedDoc(ctx context.Context, root *os.Root, name string) ([]byte, error) {
	file, err := root.Open(name)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	return contextio.ReadAll(ctx, file)
}
