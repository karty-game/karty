package project

import (
	"context"
	"fmt"
	"go/format"
	"slices"
	"strings"
	"unicode"
)

const errInvalidLevelIdentifier staticError = "level logical name cannot produce a Go identifier"

const errLevelIdentifier staticError = "level names produce the same generated Go identifier; rename a logical level"

// LevelAssetPackageFile emits typed level references from authored level manifests.
func LevelAssetPackageFile(ctx context.Context, directory, engineImport string) ([]byte, error) {
	names, err := LevelNames(ctx, directory)
	if err != nil {
		return nil, err
	}

	return levelAssetPackageFile(names, engineImport)
}

func levelAssetPackageFile(names []string, engineImport string) ([]byte, error) {
	var source strings.Builder
	source.WriteString("// Code generated by Karty. DO NOT EDIT.\n" +
		"// WARNING: DO NOT MODIFY THIS FILE DIRECTLY.\n" +
		"// WARNING: MANUAL CHANGES WILL BE OVERWRITTEN.\n" +
		"// Source of truth: levels/*/level.toml and internal/project/level_assets.go.\n" +
		"// Regenerate with: karty build\n\npackage assets\n")

	if len(names) == 0 {
		return []byte(source.String()), nil
	}

	fmt.Fprintf(&source, "\nimport engine %q\n\nconst (\n", engineImport)

	identifiers := make(map[string]string, len(names))
	for _, name := range slices.Sorted(slices.Values(names)) {
		identifier := levelIdentifier(name)
		if identifier == "Level" {
			return nil, fmt.Errorf("%q: %w", name, errInvalidLevelIdentifier)
		}

		if previous, exists := identifiers[identifier]; exists {
			return nil, fmt.Errorf("%q and %q -> %s: %w", previous, name, identifier, errLevelIdentifier)
		}

		identifiers[identifier] = name
		fmt.Fprintf(&source, "\t%s engine.LevelName = %q\n", identifier, name)
	}

	source.WriteString(")\n")

	return format.Source([]byte(source.String()))
}

func levelIdentifier(name string) string {
	var result strings.Builder
	result.WriteString("Level")

	upper := true

	for _, character := range strings.TrimPrefix(name, "levels.") {
		if !unicode.IsLetter(character) && !unicode.IsDigit(character) {
			upper = true

			continue
		}

		if upper {
			character = unicode.ToUpper(character)
			upper = false
		}

		result.WriteRune(character)
	}

	return result.String()
}
