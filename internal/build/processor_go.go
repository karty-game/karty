package build

import (
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path"
	"strings"

	"github.com/karty-game/karty/internal/packages"
)

// Explicit go/ outputs become source inside the processor's owned namespace.
// Other outputs retain their existing resource semantics. The caller publishes
// all code, assets and resources together only after every job succeeds.
func stageProcessorGo(output, processor string, files []processorFile) (map[string]bool, error) {
	if !fs.ValidPath(processor) || processor == "." || strings.ContainsAny(processor, "/\\:") {
		return nil, fmt.Errorf("%w: invalid processor source namespace", errProcessorResponse)
	}

	root, err := os.OpenRoot(output)
	if err != nil {
		return nil, err
	}
	defer root.Close()

	used := make(map[string]bool)
	packageNames := make(map[string]string)

	for _, file := range files {
		relative, generated := strings.CutPrefix(file.Path, "go/")
		if !generated {
			continue
		}

		if !fs.ValidPath(relative) || strings.ContainsAny(relative, "\\:") ||
			!strings.HasSuffix(relative, ".go") || strings.HasSuffix(relative, "_test.go") ||
			strings.HasPrefix(path.Base(relative), ".") || strings.HasPrefix(path.Base(relative), "_") {
			return nil, fmt.Errorf("%w: invalid generated Go source %q", errProcessorResponse, file.Path)
		}

		header := "// Code generated by Karty package processor " + processor + ". DO NOT EDIT.\n// Regenerate with: karty build\n"

		source, err := format.Source(append([]byte(header), file.Data...))
		if err != nil {
			return nil, fmt.Errorf("%w: invalid Go source %s: %w", errProcessorResponse, file.Path, err)
		}

		parsed, err := parser.ParseFile(token.NewFileSet(), file.Path, source, parser.PackageClauseOnly)
		if err != nil {
			return nil, err
		}

		directory := path.Dir(relative)
		if previous, exists := packageNames[directory]; parsed.Name.Name == "_" || exists && previous != parsed.Name.Name {
			return nil, fmt.Errorf("%w: inconsistent generated Go package in %s", errProcessorResponse, directory)
		}

		packageNames[directory] = parsed.Name.Name

		name := path.Join("code", processor, relative)
		if err := packages.MakeDirectories(root, path.Dir(name)); err != nil {
			return nil, err
		}

		if err := root.WriteFile(name, source, 0600); err != nil {
			return nil, err
		}

		used[file.Path] = true
	}

	return used, nil
}
