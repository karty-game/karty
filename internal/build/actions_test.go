package build

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"
)

func TestActionOnlyStagingOwnershipAndCollision(t *testing.T) {
	t.Parallel()

	root := t.TempDir()

	src := filepath.Join(root, "src")
	if err := os.Mkdir(src, 0750); err != nil {
		t.Fatal(err)
	}

	original := []byte("package main\nfunc main(){}\n")
	if err := os.WriteFile(filepath.Join(src, "main.go"), original, 0600); err != nil {
		t.Fatal(err)
	}

	actions := []byte("// Code generated by Karty. DO NOT EDIT.\npackage main\n")

	stage, cleanup, err := stageClient(root, "example.com/demo", nil, actions)
	if err != nil {
		t.Fatal(err)
	}

	generated, err := os.ReadFile(filepath.Join(stage, "karty_actions.go"))
	if err != nil || !bytes.Equal(generated, actions) {
		t.Fatal(err)
	}

	data, _ := os.ReadFile(filepath.Join(src, "main.go"))
	if !bytes.Equal(data, original) {
		t.Fatal("source changed")
	}

	cleanup()

	if _, err := os.Stat(stage); !os.IsNotExist(err) {
		t.Fatal("stage retained")
	}

	if err := os.WriteFile(filepath.Join(src, "karty_actions.go"), original, 0600); err != nil {
		t.Fatal(err)
	}

	if _, _, err := stageClient(root, "example.com/demo", nil, actions); err == nil {
		t.Fatal("authored source overwritten")
	}

	data, _ = os.ReadFile(filepath.Join(src, "karty_actions.go"))
	if !bytes.Equal(data, original) {
		t.Fatal("reserved source changed")
	}
}
