package build

import (
	"os"
	"path/filepath"
	"testing"
)

func TestRegistrationMigrationRemovesOnlyGeneratedShim(t *testing.T) {
	t.Parallel()
	directory := t.TempDir()

	path := filepath.Join(directory, "src", "karty_runtime.gen.go")
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}

	mainSource := "package main\n//go:wasmexport karty_register\nfunc main() {}\n"
	if err := os.WriteFile(filepath.Join(directory, "src", "main.go"), []byte(mainSource), 0o600); err != nil {
		t.Fatal(err)
	}

	generated := "// Code generated by Karty. DO NOT EDIT.\npackage main\n"
	if err := os.WriteFile(path, []byte(generated), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := retireLegacyGeneratedRegistration(directory); err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Fatalf("legacy generated shim still exists: %v", err)
	}
}

func TestRegistrationMigrationPreservesLegacyAndUserFiles(t *testing.T) {
	t.Parallel()

	directory := t.TempDir()

	path := filepath.Join(directory, "src", "karty_runtime.gen.go")
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}

	legacy := "// Code generated by Karty. DO NOT EDIT.\npackage main\n"

	if err := os.WriteFile(filepath.Join(directory, "src", "main.go"), []byte("package main\nfunc main() {}\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := os.WriteFile(path, []byte(legacy), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := retireLegacyGeneratedRegistration(directory); err != nil {
		t.Fatal(err)
	}

	if contents, err := os.ReadFile(path); err != nil || string(contents) != legacy {
		t.Fatalf("legacy project registration changed: %q, %v", contents, err)
	}

	userOwned := "package main\n// user-owned registration\n"
	if err := os.WriteFile(path, []byte(userOwned), 0o600); err != nil {
		t.Fatal(err)
	}

	mainPath := filepath.Join(directory, "src", "main.go")

	mainSource := "package main\n//go:wasmexport karty_register\nfunc main() {}\n"
	if err := os.WriteFile(mainPath, []byte(mainSource), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := retireLegacyGeneratedRegistration(directory); err == nil {
		t.Fatal("migration removed a user-owned registration file")
	}

	if contents, err := os.ReadFile(path); err != nil || string(contents) != userOwned {
		t.Fatalf("user-owned registration changed: %q, %v", contents, err)
	}
}

func TestRegistrationMigrationIgnoresDirectiveOutsideMainDeclaration(t *testing.T) {
	t.Parallel()

	directory := t.TempDir()

	path := filepath.Join(directory, "src", "karty_runtime.gen.go")
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}

	legacy := "// Code generated by Karty. DO NOT EDIT.\npackage main\n"
	if err := os.WriteFile(path, []byte(legacy), 0o600); err != nil {
		t.Fatal(err)
	}

	mainSource := "package main\n// Example: //go:wasmexport karty_register\nfunc main() {}\n"
	if err := os.WriteFile(filepath.Join(directory, "src", "main.go"), []byte(mainSource), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := retireLegacyGeneratedRegistration(directory); err != nil {
		t.Fatal(err)
	}

	if contents, err := os.ReadFile(path); err != nil || string(contents) != legacy {
		t.Fatalf("legacy registration changed for a documentation example: %q, %v", contents, err)
	}
}
