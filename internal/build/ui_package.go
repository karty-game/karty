package build

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/karty-game/karty-ui/codegen"
	"github.com/karty-game/karty-ui/compiler"
	"github.com/karty-game/karty-ui/schema"
)

// writeUIPackage retains inspectable Go and only replaces files owned by this generator.
func writeUIPackage(directory, module string, views []uicompiler.Component) error {
	files, err := codegen.UIPackageFiles(views, module)
	if err != nil {
		return err
	}

	for _, path := range []string{filepath.Join(directory, ".karty"), filepath.Join(directory, ".karty", "ui")} {
		if info, err := os.Lstat(path); err == nil {
			if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
				return fmt.Errorf("generated UI directory is not a regular directory: %s: %w", path, ui.ErrTemplate)
			}
		} else if !os.IsNotExist(err) {
			return err
		}
	}

	path := filepath.Join(directory, ".karty", "ui")
	if err := os.MkdirAll(path, 0o750); err != nil {
		return err
	}

	root, err := os.OpenRoot(path)
	if err != nil {
		return err
	}
	defer root.Close()

	entries, err := os.ReadDir(path)
	if err != nil {
		return err
	}
	// Preflight the whole directory before writing or retiring anything.
	if err := validateUIPackage(root, entries); err != nil {
		return err
	}

	wanted := map[string]bool{}

	for _, view := range views {
		name := "karty_ui_" + view.Name + ".go"

		wanted[name] = true
		if err := root.WriteFile(name, files[view.Source], 0o600); err != nil {
			return err
		}
	}

	for _, entry := range entries {
		if !wanted[entry.Name()] {
			if err := root.Remove(entry.Name()); err != nil {
				return err
			}
		}
	}

	return nil
}

func validateUIPackage(root *os.Root, entries []os.DirEntry) error {
	for _, entry := range entries {
		if !entry.Type().IsRegular() {
			return fmt.Errorf("unowned generated UI entry: %s: %w", entry.Name(), ui.ErrTemplate)
		}

		data, err := root.ReadFile(entry.Name())
		if err != nil {
			return err
		}

		if !strings.HasPrefix(entry.Name(), "karty_ui_") || !strings.HasSuffix(entry.Name(), ".go") ||
			!strings.HasPrefix(string(data), "// Code generated by Karty. DO NOT EDIT.\n") ||
			(!strings.Contains(string(data), "karty-ui/codegen/templates/ui-") && !strings.Contains(string(data), "cli/internal/codegen/templates/ui-")) {
			return fmt.Errorf("refusing to overwrite unowned UI file: %s: %w", entry.Name(), ui.ErrTemplate)
		}
	}

	return nil
}
