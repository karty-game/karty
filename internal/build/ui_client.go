package build

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/karty-game/karty-ui/codegen"
	"github.com/karty-game/karty-ui/compiler"
	"github.com/karty-game/karty-ui/schema"
)

// stageUIClient keeps generated same-package source outside the user-owned src
// tree. A fresh private directory prevents stale generated components surviving.
func stageUIClient(directory, module string, views []uicompiler.Component) (string, func(), error) {
	files, err := codegen.UIClientFiles(views, module)
	if err != nil {
		return "", nil, err
	}

	if len(files) == 0 {
		return "./src", func() {}, nil
	}

	root, err := filepath.Abs(directory)
	if err != nil {
		return "", nil, err
	}

	derived := filepath.Join(root, ".karty")
	if info, err := os.Lstat(derived); err == nil && info.Mode()&os.ModeSymlink != 0 {
		return "", nil, fmt.Errorf("symlinked .karty directory: %w", ui.ErrTemplate)
	}

	if err := os.MkdirAll(derived, 0o750); err != nil {
		return "", nil, err
	}

	stage, err := os.MkdirTemp(derived, "client-build-")
	if err != nil {
		return "", nil, err
	}

	cleanup := func() { _ = os.RemoveAll(stage) }
	source := filepath.Join(root, "src")

	sourceRoot, err := os.OpenRoot(source)
	if err != nil {
		cleanup()

		return "", nil, err
	}
	defer sourceRoot.Close()

	stageRoot, err := os.OpenRoot(stage)
	if err != nil {
		cleanup()

		return "", nil, err
	}
	defer stageRoot.Close()

	err = filepath.WalkDir(source, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}

		relative, err := filepath.Rel(source, path)
		if err != nil {
			return err
		}

		if entry.Type()&os.ModeSymlink != 0 {
			return fmt.Errorf("client staging does not accept symlinks: %s: %w", path, ui.ErrTemplate)
		}

		if entry.IsDir() {
			return stageRoot.MkdirAll(relative, 0o750)
		}

		if !entry.Type().IsRegular() {
			return fmt.Errorf("client staging requires regular files: %s: %w", path, ui.ErrTemplate)
		}

		data, err := sourceRoot.ReadFile(relative)
		if err != nil {
			return err
		}

		if strings.HasSuffix(path, ".go") {
			if strings.HasPrefix(filepath.Base(path), "karty_ui_") {
				return fmt.Errorf("reserved staged UI filename: %s: %w", path, ui.ErrTemplate)
			}

			data = append(
				[]byte(
					"// Code generated by Karty staging. DO NOT EDIT.\n// WARNING: DO NOT MODIFY THIS COPY.\n// WARNING: MANUAL CHANGES WILL BE LOST.\n// Source: "+path+"\n// Regenerate with: karty build\n\n//line "+path+":1\n",
				),
				data...)
		}

		return stageRoot.WriteFile(relative, data, 0o600)
	})
	if err != nil {
		cleanup()

		return "", nil, err
	}

	if err := writeLocalUI(stageRoot, views, files); err != nil {
		cleanup()

		return "", nil, err
	}

	return stage, cleanup, nil
}

func writeLocalUI(stageRoot *os.Root, views []uicompiler.Component, files map[string][]byte) error {
	for _, view := range views {
		if !view.Local {
			continue
		}

		if err := stageRoot.WriteFile("karty_ui_"+view.Name+".go", files[view.Source], 0o600); err != nil {
			return err
		}
	}

	return nil
}
