const errAudioStreamIdentifier staticError = "audio stream names produce the same generated Go identifier"

//nolint:wsl_v5,nlreturn // Generated declarations stay readable as one short deterministic routine.
func audioStreamAssetFile(typeName, prefix, sourceName, engineImport string, streams []project.AudioStream) ([]byte, error) {
	sorted := slices.Clone(streams)
	slices.SortFunc(sorted, func(a, b project.AudioStream) int { return strings.Compare(a.Name, b.Name) })
	var source strings.Builder
	fmt.Fprintf(
		&source,
		"// Code generated by Karty. DO NOT EDIT.\n// Source of truth: %s declarations in karty.toml.\n// Regenerate with: karty build\n\npackage assets\n",
		sourceName,
	)
	if len(sorted) > 0 {
		fmt.Fprintf(&source, "\nimport engine %q\n\nconst (\n", engineImport)
	}
	identifiers := make(map[string]bool, len(sorted))
	for index, stream := range sorted {
		identifier := prefix + exportedAssetIdentifier(stream.Name)
		if identifiers[identifier] {
			return nil, fmt.Errorf("%s %s: %w", sourceName, identifier, errAudioStreamIdentifier)
		}
		identifiers[identifier] = true
		fmt.Fprintf(&source, "\t%s engine.%s = %d\n", identifier, typeName, index+1)
	}
	if len(sorted) > 0 {
		source.WriteString(")\n")
	}
	return format.Source([]byte(source.String()))
}

//nolint:wsl_v5,nlreturn // Catalog construction and hashing intentionally stay adjacent.
func stageProjectAudioStreams(output, artifact string, streams []assetpipeline.AudioStream) error {
	if len(streams) == 0 {
		return nil
	}
	if len(streams) > cartridge.MaxAudioStreamCount {
		return cartridge.ErrAudioStreams
	}
	catalog := make([]cartridge.AudioStream, 0, len(streams))
	directory, err := prepareMediaDirectory(output, ".kaud", ".audio-")
	if err != nil {
		return err
	}
	for _, stream := range streams {
		entry := cartridge.AudioStream{
			ID:         stream.ID,
			Name:       stream.Name,
			Kind:       cartridge.AudioStreamKind(stream.Kind),
			Channels:   stream.Metadata.Channels,
			SampleRate: stream.Metadata.SampleRate,
			Frames:     stream.Metadata.Frames,
		}
		source, err := os.Open(stream.SourcePath)
		if err != nil {
			return fmt.Errorf("open %s %q: %w", stream.Kind, stream.Name, err)
		}
		staged, err := os.CreateTemp(directory, ".audio-*")
		if err != nil {
			_ = source.Close()
			return err
		}
		stagedName := staged.Name()
		rawDigest := sha256.New()
		entry.Size, entry.SHA256, entry.Chunks, err = writeMediaEnvelope(
			staged, io.TeeReader(source, rawDigest), cartridge.MediaKindQOAAudio,
			stream.OutputBytes, cartridge.AudioStreamChunkSize,
		)
		closeErr := errors.Join(source.Close(), staged.Close())
		if err != nil || closeErr != nil {
			_ = os.Remove(stagedName)
			return errors.Join(err, closeErr)
		}
		if hex.EncodeToString(rawDigest.Sum(nil)) != stream.OutputSHA256 {
			_ = os.Remove(stagedName)
			return errCachedAssetChanged
		}
		if err := os.Rename(stagedName, filepath.Join(output, entry.Path())); err != nil {
			_ = os.Remove(stagedName)
			return err
		}
		catalog = append(catalog, entry)
	}
	bundle, err := cartridge.EncodeAudioStreams(catalog)
	if err != nil {
		return err
	}
	wasm, err := os.ReadFile(artifact)
	if err != nil {
		return err
	}
	wasm, err = cartridge.EmbedSection(wasm, cartridge.AudioStreamSectionName, bundle)
	if err != nil {
		return err
	}
	//nolint:gosec // artifact is the fixed dist/raw/game.kart path owned by this build.
	return os.WriteFile(artifact, wasm, 0o600)
}

//nolint:wsl_v5,nlreturn // Validation and staging intentionally remain one sequential operation.
func stageAudioStreamFiles(target, artifact, raw string) error {
	directory, err := prepareMediaDirectory(target, ".kaud", ".audio-")
	if err != nil {
		return err
	}
	wasm, err := os.ReadFile(artifact)
	if err != nil {
		return err
	}
	bundle, err := cartridge.ExtractSection(wasm, cartridge.AudioStreamSectionName)
	if errors.Is(err, cartridge.ErrSectionMissing) {
		return nil
	}
	if err != nil {
		return err
	}
	streams, err := cartridge.DecodeAudioStreams(bundle)
	if err != nil {
		return err
	}
	seen := make(map[string]bool)
	for _, stream := range streams {
		if seen[stream.Path()] {
			continue
		}
		seen[stream.Path()] = true
		if err := copyFile(filepath.Join(raw, stream.Path()), filepath.Join(directory, filepath.Base(stream.Path())), 0o600); err != nil {
			return err
		}
	}
	return nil
}
