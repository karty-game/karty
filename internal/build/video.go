const (
	errVideoIdentifier staticError = "video names produce the same generated Go identifier"
	maxMPEGHeader                  = 128 << 10
)

//nolint:wsl_v5,nlreturn // Generated declarations are a compact deterministic routine.
func videoAssetFile(videos []project.Video, engineImport string) ([]byte, error) {
	sorted := slices.Clone(videos)
	slices.SortFunc(sorted, func(a, b project.Video) int { return strings.Compare(a.Name, b.Name) })
	var source strings.Builder
	source.WriteString(
		"// Code generated by Karty. DO NOT EDIT.\n// Source of truth: video declarations in karty.toml.\n// Regenerate with: karty build\n\npackage assets\n",
	)
	if len(sorted) > 0 {
		fmt.Fprintf(&source, "\nimport engine %q\n\nconst (\n", engineImport)
	}
	identifiers := make(map[string]bool, len(sorted))
	for index, video := range sorted {
		identifier := "Video" + exportedAssetIdentifier(video.Name)
		if identifiers[identifier] {
			return nil, fmt.Errorf("%s: %w", identifier, errVideoIdentifier)
		}
		identifiers[identifier] = true
		fmt.Fprintf(&source, "\t%s engine.VideoID = %d\n", identifier, index+1)
	}
	if len(sorted) > 0 {
		source.WriteString(")\n")
	}
	return format.Source([]byte(source.String()))
}

//nolint:wsl_v5 // Catalog construction and staging intentionally stay adjacent.
func stageProjectVideos(directory, output, artifact string, videos []project.Video) error {
	if len(videos) > cartridge.MaxVideoCount {
		return cartridge.ErrVideos
	}
	sorted := slices.Clone(videos)
	slices.SortFunc(sorted, func(a, b project.Video) int { return strings.Compare(a.Name, b.Name) })
	root, err := os.OpenRoot(directory)
	if err != nil {
		return err
	}
	defer root.Close()
	if _, err := prepareMediaDirectory(output, ".kvid", ".video-"); err != nil {
		return err
	}
	catalog := make([]cartridge.Video, 0, len(sorted))
	for index, video := range sorted {
		entry, err := stageVideoSource(root, output, video.Source)
		if err != nil {
			return fmt.Errorf("video %q: %w", video.Name, err)
		}
		entry.ID, entry.Name = uint32(index+1), video.Name
		catalog = append(catalog, entry)
	}
	bundle, err := cartridge.EncodeVideos(catalog)
	if err != nil {
		return err
	}
	wasm, err := os.ReadFile(artifact)
	if err != nil {
		return err
	}
	wasm, err = cartridge.EmbedSection(wasm, cartridge.VideoSectionName, bundle)
	if err != nil {
		return err
	}
	//nolint:gosec // artifact is the fixed dist/raw/game.kart path owned by this build.
	return os.WriteFile(artifact, wasm, 0o600)
}

//nolint:wsl_v5,nlreturn // Chunk hashing is easier to audit as one sequential operation.
func stageVideoSource(root *os.Root, output, path string) (cartridge.Video, error) {
	source, err := root.Open(path)
	if err != nil {
		return cartridge.Video{}, err
	}
	defer source.Close()
	info, err := source.Stat()
	if err != nil || !info.Mode().IsRegular() || info.Size() < 4 || info.Size() > cartridge.MaxVideoPayloadSize {
		return cartridge.Video{}, cartridge.ErrVideos
	}
	directory := filepath.Join(output, mediaContentDirectory)
	staged, err := os.CreateTemp(directory, ".video-*")
	if err != nil {
		return cartridge.Video{}, err
	}
	defer os.Remove(staged.Name())
	defer staged.Close()
	header := make([]byte, min(info.Size(), maxMPEGHeader))
	if _, err := io.ReadFull(source, header); err != nil || !validMPEG1Video(header) {
		return cartridge.Video{}, cartridge.ErrVideos
	}
	if _, err := source.Seek(0, 0); err != nil {
		return cartridge.Video{}, err
	}
	entry := cartridge.Video{}
	entry.Size, entry.SHA256, entry.Chunks, err = writeMediaEnvelope(
		staged, source, cartridge.MediaKindMPEG1Video, info.Size(), cartridge.VideoChunkSize,
	)
	if err != nil {
		return cartridge.Video{}, err
	}
	if err := staged.Close(); err != nil {
		return cartridge.Video{}, err
	}
	if err := os.Rename(staged.Name(), filepath.Join(output, entry.Path())); err != nil {
		return cartridge.Video{}, err
	}
	return entry, nil
}

//nolint:mnd // MPEG sequence header offsets and bit widths come from the MPEG-1 format.
func validMPEG1Video(header []byte) bool {
	if len(header) < 12 || !bytes.Equal(header[:4], []byte{0, 0, 1, 0xba}) || header[4]&0xf0 != 0x20 {
		return false
	}

	sequence := bytes.Index(header, []byte{0, 0, 1, 0xb3})
	if sequence < 0 || sequence+8 > len(header) {
		return false
	}

	width := int(header[sequence+4])<<4 | int(header[sequence+5])>>4

	height := int(header[sequence+5]&0x0f)<<8 | int(header[sequence+6])
	if width == 0 || height == 0 || width > 1280 || height > 720 {
		return false
	}

	for offset := sequence + 8; offset+4 < len(header); offset++ {
		if bytes.Equal(header[offset:offset+4], []byte{0, 0, 1, 0xb5}) && header[offset+4]>>4 == 1 {
			return false
		}
	}

	return true
}

//nolint:wsl_v5,nlreturn // Catalog validation and file staging form one operation.
func stageVideoFiles(target, artifact, raw string) error {
	directory, err := prepareMediaDirectory(target, ".kvid", ".video-")
	if err != nil {
		return err
	}
	wasm, err := os.ReadFile(artifact)
	if err != nil {
		return err
	}
	bundle, err := cartridge.ExtractSection(wasm, cartridge.VideoSectionName)
	if errors.Is(err, cartridge.ErrSectionMissing) {
		return nil
	}
	if err != nil {
		return err
	}
	videos, err := cartridge.DecodeVideos(bundle)
	if err != nil {
		return err
	}
	for _, video := range videos {
		if err := copyFile(filepath.Join(raw, video.Path()), filepath.Join(directory, filepath.Base(video.Path())), 0o600); err != nil {
			return err
		}
	}
	return nil
}
