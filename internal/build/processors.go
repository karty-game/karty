const processorMaxBytes = 16 << 20
const processorMaxFiles = 256
const processorMaxUses = 16
const processorFileHeaderBytes = 6
const processorDiagnosticMaxBytes = 64 << 10
const processorOutputMaxBytes = processorMaxBytes * 2
const processorMarker = "karty-processed@1\n"

const (
	errProcessor          staticError = "invalid build processor"
	errProcessorResponse  staticError = "invalid processor response"
	errProcessorOwnership staticError = "processor output directory is not owned"
)

type processorUse struct {
	Use    string   `toml:"use"`
	Inputs []string `toml:"inputs"`
}

type processorFile struct {
	Path string
	Data []byte
}

type processorJob struct {
	name       string
	tool       *packages.Resolved
	definition packages.Processor
	request    []byte
}

type processorRunner func(context.Context, string, []string, []byte) ([]byte, error)

// runProcessors prepares every input before running any tool. Results replace
// only an owned generated package, after every processor has succeeded.
func runProcessors(ctx context.Context, directory string, set *packages.Set) error {
	return runProcessorsWith(ctx, directory, set, executeProcessor)
}

func runProcessorsWith(ctx context.Context, directory string, set *packages.Set, run processorRunner) error {
	root, err := os.OpenRoot(directory)
	if err != nil {
		return err
	}

	defer root.Close()

	manifest, err := packages.Read(ctx, root, "karty.toml", packages.MaxManifestBytes)
	if err != nil {
		return err
	}

	var config struct {
		Build struct {
			Processors []processorUse `toml:"processors"`
		} `toml:"build"`
	}

	if err := toml.NewDecoder(bytes.NewReader(manifest)).Decode(&config); err != nil {
		return err
	}

	if len(config.Build.Processors) > processorMaxUses {
		return fmt.Errorf("%w: at most 16 project build processors", errProcessor)
	}

	if err := checkProcessorOwnership(root); err != nil {
		return err
	}

	jobs, err := prepareProcessorJobs(ctx, root, set, config.Build.Processors)
	if err != nil {
		return err
	}

	if len(jobs) == 0 {
		// Remove stale generated resources through the same owned transaction.
		if _, err := root.Lstat(".karty/processed"); os.IsNotExist(err) {
			return nil
		}
	}

	if err := packages.MakeDirectories(root, ".karty"); err != nil {
		return err
	}

	work, err := os.MkdirTemp(filepath.Join(directory, ".karty"), "processor-build-")
	if err != nil {
		return err
	}

	defer os.RemoveAll(work)

	output := filepath.Join(work, "processed")
	if err := os.Mkdir(output, 0700); err != nil {
		return err
	}

	if err := os.Mkdir(filepath.Join(output, "data"), 0700); err != nil {
		return err
	}

	var declarations, lookups strings.Builder

	for index, job := range jobs {
		tool := filepath.Join(work, fmt.Sprintf("tool-%d", index))
		if err := copyProcessorTool(ctx, job.tool.Root, tool); err != nil {
			return fmt.Errorf("processor %s: %w", job.name, err)
		}

		toolCtx, cancel := context.WithTimeout(ctx, 60*time.Second)
		encoded, runErr := run(toolCtx, tool, job.definition.Command, job.request)

		cancel()

		if runErr != nil {
			return fmt.Errorf("processor %s: %w", job.name, runErr)
		}

		files, err := decodeProcessorResponse(encoded)
		if err != nil {
			return fmt.Errorf("processor %s: %w", job.name, err)
		}

		for _, file := range files {
			digest := sha256.Sum256([]byte(job.name + "\x00" + file.Path))

			identifier := "p" + hex.EncodeToString(digest[:])
			if err := os.WriteFile(filepath.Join(output, "data", identifier), file.Data, 0600); err != nil {
				return err
			}

			fmt.Fprintf(&declarations, "//go:embed data/%s\nvar %s []byte\n", identifier, identifier)
			fmt.Fprintf(&lookups, "case %s: return append([]byte(nil), %s...), true\n", strconv.Quote(job.name+"/"+file.Path), identifier)
		}
	}

	imports := ""
	if declarations.Len() != 0 {
		imports = "import _ \"embed\"\n"
	}

	source := "// Code generated by Karty package processors. DO NOT EDIT.\n// Regenerate with: karty build\npackage processed\n" + imports + declarations.String() + "\n// Read returns an owned copy of a processor output.\nfunc Read(processor, name string) ([]byte, bool) { switch processor+\"/\"+name {\n" + lookups.String() + "}; return nil, false }\n"
	if err := os.WriteFile(filepath.Join(output, "processed.go"), []byte(source), 0600); err != nil {
		return err
	}

	if err := os.WriteFile(filepath.Join(output, ".owner"), []byte(processorMarker), 0600); err != nil {
		return err
	}

	return publishProcessorOutput(root, filepath.ToSlash(filepath.Join(filepath.Base(work), "processed")))
}

func prepareProcessorJobs(ctx context.Context, root *os.Root, set *packages.Set, uses []processorUse) ([]processorJob, error) {
	var jobs []processorJob

	seen := map[string]bool{}

	for _, use := range uses {
		packageName, processorName, found := strings.Cut(use.Use, ".")
		if !found || seen[use.Use] || len(use.Inputs) == 0 || len(use.Inputs) > processorMaxFiles {
			return nil, fmt.Errorf("%w: invalid processor selection %q", errProcessor, use.Use)
		}

		seen[use.Use] = true

		item := set.Items[packageName]
		if item == nil {
			return nil, fmt.Errorf("%w: processor %q: package is not imported", errProcessor, use.Use)
		}

		var definition *packages.Processor

		for index := range item.Manifest.Processors {
			if item.Manifest.Processors[index].Name == processorName {
				definition = &item.Manifest.Processors[index]
			}
		}

		if definition == nil {
			return nil, fmt.Errorf("%w: unknown processor %q", errProcessor, use.Use)
		}

		files, err := processorInputs(ctx, root, use.Inputs)
		if err != nil {
			return nil, fmt.Errorf("processor %s inputs: %w", use.Use, err)
		}

		request, err := encodeProcessorFiles(files)
		if err != nil {
			return nil, err
		}

		jobs = append(jobs, processorJob{use.Use, item, *definition, request})
	}

	return jobs, nil
}

func processorInputs(ctx context.Context, root *os.Root, patterns []string) ([]processorFile, error) {
	names := map[string]bool{}

	for _, pattern := range patterns {
		if !fs.ValidPath(pattern) || pattern == "." || strings.ContainsAny(pattern, "\\:") || strings.HasPrefix(pattern, ".karty/") ||
			strings.HasPrefix(pattern, "dist/") {
			return nil, fmt.Errorf("%w: input must be a confined authored path: %q", errProcessor, pattern)
		}

		matches, err := fs.Glob(root.FS(), pattern)
		if err != nil {
			return nil, err
		}

		if len(matches) == 0 {
			return nil, fmt.Errorf("%w: input matches no files: %q", errProcessor, pattern)
		}

		for _, name := range matches {
			for component := range strings.SplitSeq(name, "/") {
				switch component {
				case ".karty", "dist", ".git", ".codex", ".agents":
					return nil, fmt.Errorf("%w: input is generated or private: %s", errProcessor, name)
				}
			}

			names[name] = true
		}
	}

	if len(names) > processorMaxFiles {
		return nil, fmt.Errorf("%w: too many processor inputs", errProcessor)
	}

	ordered := make([]string, 0, len(names))
	for name := range names {
		ordered = append(ordered, name)
	}

	slices.Sort(ordered)

	var files []processorFile

	total := 0

	for _, name := range ordered {
		info, err := root.Lstat(name)
		if err != nil {
			return nil, err
		}

		if !info.Mode().IsRegular() {
			return nil, fmt.Errorf("%w: input is not a regular file: %s", errProcessor, name)
		}

		data, err := packages.Read(ctx, root, name, processorMaxBytes)
		if err != nil {
			return nil, err
		}

		total += len(data)
		if total > processorMaxBytes {
			return nil, fmt.Errorf("%w: processor inputs exceed 16 MiB", errProcessor)
		}

		files = append(files, processorFile{Path: name, Data: data})
	}

	return files, nil
}

func copyProcessorTool(ctx context.Context, root *os.Root, destination string) error {
	if err := os.Mkdir(destination, 0700); err != nil {
		return err
	}

	count, total := 0, int64(0)

	return fs.WalkDir(root.FS(), ".", func(name string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}

		if err := ctx.Err(); err != nil {
			return err
		}

		if entry.IsDir() {
			switch path.Base(name) {
			case ".git", ".karty", "dist", ".codex", ".agents", "node_modules", "bin", "obj":
				return fs.SkipDir
			}

			if name == "." {
				return nil
			}

			return os.MkdirAll(filepath.Join(destination, filepath.FromSlash(name)), 0700)
		}

		if !entry.Type().IsRegular() {
			return fmt.Errorf("%w: processor source is not a regular file: %s", errProcessor, name)
		}

		count++
		if count > packages.MaxFiles {
			return packages.ErrPackage
		}

		data, err := packages.Read(ctx, root, name, packages.MaxFileBytes)
		if err != nil {
			return err
		}

		total += int64(len(data))
		if total > packages.MaxTotalBytes {
			return packages.ErrPackage
		}

		return os.WriteFile(filepath.Join(destination, filepath.FromSlash(name)), data, 0600)
	})
}

// KPR1 is a bounded binary envelope, shared by requests and responses. File
// names are logical UTF-8 paths, never output filesystem destinations.
func encodeProcessorFiles(files []processorFile) ([]byte, error) {
	output := []byte{'K', 'P', 'R', '1', 0, 0, 0, 0}
	binary.LittleEndian.PutUint32(output[4:], uint32(len(files)))

	for _, file := range files {
		output = binary.LittleEndian.AppendUint16(output, uint16(len(file.Path)))
		output = binary.LittleEndian.AppendUint32(output, uint32(len(file.Data)))
		output = append(output, file.Path...)
		output = append(output, file.Data...)
	}

	if _, err := decodeProcessorResponse(output); err != nil {
		return nil, err
	}

	return output, nil
}

func decodeProcessorResponse(encoded []byte) ([]processorFile, error) {
	if len(encoded) < 8 || len(encoded) > processorMaxBytes+processorMaxFiles*262+8 || string(encoded[:4]) != "KPR1" {
		return nil, fmt.Errorf("%w: invalid processor envelope", errProcessorResponse)
	}

	count := binary.LittleEndian.Uint32(encoded[4:])
	if count > processorMaxFiles {
		return nil, fmt.Errorf("%w: too many processor files", errProcessorResponse)
	}

	files := make([]processorFile, 0, int(count))
	encoded = encoded[8:]
	seen := map[string]bool{}
	total := 0

	for range count {
		if len(encoded) < processorFileHeaderBytes {
			return nil, fmt.Errorf("%w: truncated processor file", errProcessorResponse)
		}

		nameSize := int(binary.LittleEndian.Uint16(encoded))
		dataSize := uint64(binary.LittleEndian.Uint32(encoded[2:]))

		encoded = encoded[processorFileHeaderBytes:]
		if nameSize == 0 || nameSize > 256 || uint64(nameSize)+dataSize > uint64(len(encoded)) {
			return nil, fmt.Errorf("%w: invalid processor file bounds", errProcessorResponse)
		}

		name := string(encoded[:nameSize])
		if !utf8.ValidString(name) || !fs.ValidPath(name) || name == "." || strings.ContainsAny(name, "\\:") || seen[name] {
			return nil, fmt.Errorf("%w: invalid or duplicate output %q", errProcessorResponse, name)
		}

		seen[name] = true

		total += int(dataSize)
		if total > processorMaxBytes {
			return nil, fmt.Errorf("%w: processor files exceed 16 MiB", errProcessorResponse)
		}

		files = append(files, processorFile{Path: name, Data: encoded[nameSize : nameSize+int(dataSize)]})
		encoded = encoded[nameSize+int(dataSize):]
	}

	if len(encoded) != 0 {
		return nil, fmt.Errorf("%w: trailing processor bytes", errProcessorResponse)
	}

	slices.SortFunc(files, func(a, b processorFile) int { return strings.Compare(a.Path, b.Path) })

	return files, nil
}

type processorBuffer struct {
	bytes.Buffer

	limit int
}

func (buffer *processorBuffer) Write(data []byte) (int, error) {
	if len(data) > buffer.limit-buffer.Len() {
		return 0, fmt.Errorf("%w: processor output exceeds limit", errProcessor)
	}

	return buffer.Buffer.Write(data)
}

func executeProcessor(ctx context.Context, directory string, argv []string, input []byte) ([]byte, error) {
	command := process.CommandContext(ctx, argv[0], argv[1:]...)
	command.Dir = directory

	command.Env = append(
		os.Environ(),
		"GOWORK=off",
		"DOTNET_NOLOGO=1",
		"DOTNET_CLI_TELEMETRY_OPTOUT=1",
		"DOTNET_SKIP_FIRST_TIME_EXPERIENCE=1",
	)
	command.Stdin = bytes.NewReader(input)
	output := &processorBuffer{limit: processorOutputMaxBytes}
	diagnostic := &processorBuffer{limit: processorDiagnosticMaxBytes}
	command.Stdout = output

	command.Stderr = diagnostic
	if err := command.Run(); err != nil {
		return nil, fmt.Errorf("%w: %s", err, diagnostic.String())
	}

	return output.Bytes(), nil
}

func checkProcessorOwnership(root *os.Root) error {
	info, err := root.Lstat(".karty/processed")
	if os.IsNotExist(err) {
		return nil
	}

	if err != nil {
		return err
	}

	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return errProcessorOwnership
	}

	marker, err := root.ReadFile(".karty/processed/.owner")
	if err != nil || string(marker) != processorMarker {
		return errProcessorOwnership
	}

	return nil
}

func publishProcessorOutput(root *os.Root, relative string) error {
	const target = ".karty/processed"

	if _, err := root.Lstat(target); os.IsNotExist(err) {
		return root.Rename(".karty/"+relative, target)
	} else if err != nil {
		return err
	}

	if err := checkProcessorOwnership(root); err != nil {
		return err
	}

	backup := ".karty/" + path.Dir(relative) + "/previous"
	if err := root.Rename(target, backup); err != nil {
		return err
	}

	if err := root.Rename(".karty/"+relative, target); err != nil {
		_ = root.Rename(backup, target)

		return err
	}

	return nil
}
