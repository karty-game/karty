//go:build ignore

// Own the reactor cap and barrel hoop bevels without rewriting other authoring.
// Run from the CLI root with mise run generate-hangar-heroes; -check verifies drift.
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"math"
	"os"
	"strings"

	"github.com/karty-game/karty/internal/sampleformat"
)

type heroPoint struct{ x, y float64 }

func main() {
	check := flag.Bool("check", false, "verify generated hero trim without writing")
	flag.Parse()
	if err := generateHeroTrim(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generateHeroTrim(check bool) error {
	const path = "samples/hangar/levels/hangar/world.yaml"
	original, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	text := string(original)
	for _, trim := range []struct {
		id                             string
		x, y, radius, low, high, bevel float64
		collision                      bool
	}{
		{"inspection-barrel-upper-hoop", 14.8, -1.55, .402, .84, .89, .008, false},
		{"core-cap", 8, 24, 2.4, 5.5, 5.85, .045, true},
	} {
		start, end, err := heroBlock(text, trim.id)
		if err != nil {
			return err
		}
		var generated bytes.Buffer
		fmt.Fprintf(&generated, "  # BEGIN HERO TRIM: %s\n", trim.id)
		outer := make([]heroPoint, 12)
		for index := range outer {
			angle := float64(index) * 2 * math.Pi / float64(len(outer))
			outer[index] = heroPoint{
				math.Round((trim.x+trim.radius*math.Cos(angle))*1e4) / 1e4,
				math.Round((trim.y+trim.radius*math.Sin(angle))*1e4) / 1e4,
			}
		}
		writeHeroBevel(&generated, trim.id, outer, trim.low, trim.high, trim.bevel, trim.collision)
		fmt.Fprintf(&generated, "  # END HERO TRIM: %s\n", trim.id)
		text = text[:start] + generated.String() + text[end:]
	}
	for _, id := range []string{"inspection-barrel-lower-hoop", "inspection-barrel-rim-0", "inspection-barrel-rim-1", "inspection-barrel-rim-2", "inspection-barrel-rim-3", "inspection-barrel-rim-4", "inspection-barrel-rim-5", "inspection-barrel-rim-6", "inspection-barrel-rim-7", "inspection-barrel-rim-8", "inspection-barrel-rim-9", "inspection-barrel-rim-10", "inspection-barrel-rim-11"} {
		text, err = heroMaterial(text, id, "steel", "hero-steel")
		if err != nil {
			return err
		}
	}
	text, err = heroMaterial(text, "inspection-burning-barrel", "side_material: ribbed", "side_material: barrel-painted")
	if err != nil {
		return err
	}
	formatted, err := sampleformat.YAML(context.Background(), []byte(text))
	if err != nil {
		return err
	}
	if check {
		if !bytes.Equal(original, formatted) {
			return fmt.Errorf("hero trim is stale; run mise run generate-hangar-heroes")
		}
		return nil
	}
	return os.WriteFile(path, formatted, 0o644)
}

func heroBlock(text, id string) (int, int, error) {
	begin, finish := "  # BEGIN HERO TRIM: "+id+"\n", "  # END HERO TRIM: "+id+"\n"
	if start := strings.Index(text, begin); start >= 0 {
		end := strings.Index(text[start:], finish)
		if end < 0 {
			return 0, 0, fmt.Errorf("incomplete hero trim block %s", id)
		}
		return start, start + end + len(finish), nil
	}
	start := strings.Index(text, "  - id: "+id+"\n")
	if start < 0 {
		return 0, 0, fmt.Errorf("missing hero solid %s", id)
	}
	end := strings.Index(text[start+1:], "\n  - id: ")
	if end < 0 {
		return 0, 0, fmt.Errorf("missing solid after %s", id)
	}
	return start, start + 1 + end + 1, nil
}

func heroMaterial(text, id, before, after string) (string, error) {
	start, end, err := heroBlock(text, id)
	if err != nil {
		return "", err
	}
	if !strings.Contains(before, ":") {
		before, after = ": "+before+"\n", ": "+after+"\n"
	}
	return text[:start] + strings.ReplaceAll(text[start:end], before, after) + text[end:], nil
}

func writeHeroBevel(out *bytes.Buffer, id string, outer []heroPoint, low, high, bevel float64, collision bool) {
	if collision {
		// The sample's stepping data requires flat caps for collidable solids.
		// Chamfer vertical corners inside the original footprint instead.
		clipped := make([]heroPoint, 0, len(outer)*2)
		for index, p := range outer {
			for _, neighbor := range []heroPoint{outer[(index+len(outer)-1)%len(outer)], outer[(index+1)%len(outer)]} {
				length := math.Hypot(neighbor.x-p.x, neighbor.y-p.y)
				clipped = append(clipped, heroPoint{p.x + bevel*(neighbor.x-p.x)/length, p.y + bevel*(neighbor.y-p.y)/length})
			}
		}
		writeHeroSolid(out, id, clipped, low, fmt.Sprintf("{c: %g}", high), true)
		return
	}
	inner, normals := make([]heroPoint, len(outer)), make([]heroPoint, len(outer))
	for index, p := range outer {
		next := outer[(index+1)%len(outer)]
		length := math.Hypot(next.x-p.x, next.y-p.y)
		normals[index] = heroPoint{-(next.y - p.y) / length, (next.x - p.x) / length}
	}
	for index, p := range outer {
		previous, current := normals[(index+len(outer)-1)%len(outer)], normals[index]
		determinant := previous.x*current.y - previous.y*current.x
		inner[index] = heroPoint{p.x + bevel*(current.y-previous.y)/determinant, p.y + bevel*(previous.x-current.x)/determinant}
	}
	writeHeroSolid(out, id, inner, low, fmt.Sprintf("{c: %g}", high), collision)
	for index, p := range outer {
		next, normal := (index+1)%len(outer), normals[index]
		cap := fmt.Sprintf("{a: %g, b: %g, c: %g}", normal.x, normal.y, high-bevel-normal.x*p.x-normal.y*p.y)
		writeHeroSolid(
			out,
			fmt.Sprintf("%s-bevel-%d", id, index),
			[]heroPoint{p, outer[next], inner[next], inner[index]},
			low,
			cap,
			collision,
		)
	}
}

func writeHeroSolid(out *bytes.Buffer, id string, points []heroPoint, low float64, cap string, collision bool) {
	fmt.Fprintf(out, "  - id: %s\n    footprint: [", id)
	for index, p := range points {
		if index > 0 {
			out.WriteString(", ")
		}
		fmt.Fprintf(out, "{x: %g, y: %g}", p.x, p.y)
	}
	fmt.Fprintf(
		out,
		"]\n    bottom: {c: %g}\n    top: %s\n    side_material: hero-steel\n    top_material: hero-steel\n    bottom_material: hero-steel\n    collision: %t\n",
		low,
		cap,
		collision,
	)
}
