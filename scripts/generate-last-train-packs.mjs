// Author-owned inventory -> ordinary level manifests, themes and static UI sources.
// Artwork lives only in its owning level directory; no alternate loader or codec.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";
const root = resolve("samples/last-train");
const packs = JSON.parse(readFileSync(resolve(root, "art-packs.json"), "utf8"));
const catalog = [];
const names = new Set();
for (const [pack, entries] of Object.entries(packs)) {
  const dir = resolve(root, "levels", pack);
  mkdirSync(dir, { recursive: true });
  const sorted = entries.toSorted((a, b) => a.name.localeCompare(b.name, "en"));
  let manifest = `# Generated by scripts/generate-last-train-packs.mjs from art-packs.json.\n[level]\nname = "art.${pack}"\nkind = "presentation"\n\n[theme]\nsource = "theme.toml"\n`;
  let theme = 'extends = "dark"\n';
  for (const [index, art] of sorted.entries()) {
    if (names.has(art.name)) throw Error(`duplicate art owner: ${art.name}`);
    names.add(art.name);
    manifest += `\n[[textures]]\nname = "${art.name}"\nsource = "${art.file}"\nprofile = "interface"\n[textures.transform]\nmax_width = ${art.width}\nmax_height = ${art.height}\n\n[[ui]]\nname = "art.${art.name}"\nsource = "${art.name}.kui"\n`;
    theme += `\n[images.${art.name}]\nasset = "${art.name}"\nslice = [0, 0, 0, 0]\n`;
    writeFileSync(
      resolve(dir, `${art.name}.kui`),
      `<template>\n  <panel class="picture"><image/></panel>\n</template>\n<style>\n.picture\n  width: 100%\n  height: 100%\n  padding: 0\nimage\n  width: 100%\n  height: 100%\n  image: theme.images.${art.name}\n  image-fit: ${art.height === 720 ? "cover" : "contain"}\n</style>\n`,
    );
    catalog.push(`\t${JSON.stringify(art.name)}: {pack: ${JSON.stringify(pack)}, id: ${index + 1}},`);
  }
  writeFileSync(resolve(dir, "level.toml"), manifest);
  writeFileSync(resolve(dir, "theme.toml"), theme);
}
mkdirSync(resolve(root, "internal/art"), { recursive: true });
writeFileSync(
  resolve(root, "internal/art/catalog.go"),
  `// Code generated by scripts/generate-last-train-packs.mjs. DO NOT EDIT.\npackage art\n\nvar catalog = map[string]asset{\n${catalog.join("\n")}\n}\n`,
);

const formatted = spawnSync("gofmt", ["-w", resolve(root, "internal/art/catalog.go")], { stdio: "inherit" });
if (formatted.error) throw formatted.error;
if (formatted.status !== 0) process.exit(formatted.status || 1);
