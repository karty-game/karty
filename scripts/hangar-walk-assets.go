//go:build ignore

// Compile Hangar's authored floors, directed portals and collision solids into
// cartridge-local step assistance. No host or private engine source is used.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"

	"github.com/karty-game/karty/internal/worldbuild/geometry"
	"github.com/karty-game/karty/internal/worldbuild/source"
	"github.com/pelletier/go-toml/v2"
)

func main() {
	check := flag.Bool("check", false, "verify compiled walking support without writing")
	flag.Parse()
	if err := generate(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(check bool) error {
	const root = "samples/hangar/levels/hangar"
	input, err := os.ReadFile(root + "/level.toml")
	if err != nil {
		return err
	}
	var manifest struct{ Textures []struct{ Name string } }
	if err := toml.Unmarshal(input, &manifest); err != nil {
		return err
	}
	materials := map[string]uint32{}
	for index, texture := range manifest.Textures {
		materials[texture.Name] = uint32(index + 1)
	}
	expanded, err := source.Load(root, "world.yaml")
	if err != nil {
		return err
	}
	world, err := geometry.Compile(expanded, materials)
	if err != nil {
		return err
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by scripts/hangar-walk-assets.go; DO NOT EDIT.\npackage fps")
	fmt.Fprintf(&out, "const walkCellCount = %d\nvar walkCells = [...]walkCell{\n", len(world.Sectors))
	for _, cell := range world.Sectors {
		fmt.Fprintf(&out, "{name:%q,floor:%g,ceiling:%g", cell.ID, cell.Floor.C, cell.Ceiling.C)
		if cell.Floor.A != 0 || cell.Floor.B != 0 || cell.Ceiling.A != 0 || cell.Ceiling.B != 0 {
			fmt.Fprintf(&out, ",floorA:%g,floorB:%g,ceilingA:%g,ceilingB:%g", cell.Floor.A, cell.Floor.B, cell.Ceiling.A, cell.Ceiling.B)
		}
		fmt.Fprintln(&out, ",walls:[]walkWall{")
		for _, wall := range cell.Walls {
			portal := wall.Portal
			// Directed/collocated portals remain directed. Transformed portals
			// are deliberately ineligible for cartridge-local upward assistance.
			if portal >= 0 {
				other := world.Sectors[portal].Walls[wall.PortalWall-1]
				if other.Start != wall.End || other.End != wall.Start {
					portal = -1
				}
			}
			fmt.Fprintf(
				&out,
				"{a:walkPoint{%g,%g},b:walkPoint{%g,%g},portal:%d},\n",
				wall.Start.X,
				wall.Start.Y,
				wall.End.X,
				wall.End.Y,
				portal,
			)
		}
		fmt.Fprintln(&out, "}},")
	}
	fmt.Fprintln(&out, "}\nvar walkSolids = [...]walkSolid{")
	if world.StaticSolids != nil {
		for _, solid := range world.StaticSolids.Items {
			if !solid.Collision {
				continue
			}
			if solid.Bottom.A != 0 || solid.Bottom.B != 0 || solid.Top.A != 0 || solid.Top.B != 0 {
				return fmt.Errorf("step clearance requires flat solid planes: %s", solid.ID)
			}
			fmt.Fprintf(&out, "{bottom:%g,top:%g,points:[]walkPoint{", solid.Bottom.C, solid.Top.C)
			for _, point := range solid.Footprint {
				fmt.Fprintf(&out, "{%g,%g},", point.X, point.Y)
			}
			fmt.Fprintln(&out, "}},")
		}
	}
	fmt.Fprintln(&out, "}")
	data, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	const path = "samples/hangar/internal/fps/walk_world.generated.go"
	if check {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, data) {
			return fmt.Errorf("%s is stale; regenerate Hangar walk support", path)
		}
		return nil
	}
	return os.WriteFile(path, data, 0644)
}
