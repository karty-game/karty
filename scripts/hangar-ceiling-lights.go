//go:build ignore

// Own the suspended fixtures above Hangar's steady overhead point lights.
// Run from the CLI root with mise run generate-hangar-ceiling-lights.
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/karty-game/karty/internal/sampleformat"
	"github.com/karty-game/karty/internal/worldbuild/source"
)

func main() {
	check := flag.Bool("check", false, "verify generated ceiling fixtures without writing")
	flag.Parse()
	if err := generateCeilingLights(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generateCeilingLights(check bool) error {
	const root = "samples/hangar/levels/hangar"
	const begin, end = "  # BEGIN CEILING FIXTURES\n", "  # END CEILING FIXTURES\n"
	original, err := os.ReadFile(root + "/world.yaml")
	if err != nil {
		return err
	}
	expanded, err := source.Load(root, "world.yaml")
	if err != nil {
		return err
	}
	if expanded.Lighting == nil {
		return fmt.Errorf("ceiling fixtures require authored lighting")
	}
	var generated bytes.Buffer
	generated.WriteString(begin)
	for _, fixture := range []struct {
		light, room string
		broken      bool
	}{
		{"arrival-key", "arrival", false},
		{"ventilation-fill", "arrival", true},
		{"window-key", "window-bay", false},
		{"reactor-overhead", "reactor", false},
		{"control-fill", "control", false},
		{"loading-key", "loading", false},
		{"extraction-key", "extraction", false},
		{"acid-control-key", "acid-control", false},
	} {
		ceiling, found := 0.0, false
		for _, room := range expanded.Rooms {
			if room.ID == fixture.room {
				if room.Ceiling.A != 0 || room.Ceiling.B != 0 {
					return fmt.Errorf("fixture %s requires a flat ceiling", fixture.light)
				}
				ceiling, found = room.Ceiling.C, true
			}
		}
		if !found {
			return fmt.Errorf("missing fixture room %s", fixture.room)
		}
		found = false
		for _, light := range expanded.Lighting.Lights {
			if light.ID == fixture.light {
				if fixture.broken && (light.Color.X != 0 || light.Color.Y != 0 || light.Color.Z != 0) {
					return fmt.Errorf("broken fixture %s must have no light contribution", fixture.light)
				}
				if light.Position.Z+.25 >= ceiling {
					return fmt.Errorf("fixture %s has no suspension clearance", fixture.light)
				}
				writeCeilingFixture(
					&generated,
					fixture.light,
					light.Position.X,
					light.Position.Y,
					light.Position.Z,
					ceiling,
					fixture.broken,
				)
				found = true
			}
		}
		if !found {
			return fmt.Errorf("missing fixture light %s", fixture.light)
		}
	}
	generated.WriteString(end)
	text := string(original)
	if start := strings.Index(text, begin); start >= 0 {
		finish := strings.Index(text[start:], end)
		if finish < 0 {
			return fmt.Errorf("incomplete ceiling fixture block")
		}
		text = text[:start] + generated.String() + text[start+finish+len(end):]
	} else {
		const solids = "\nsolids:\n"
		if !strings.Contains(text, solids) {
			return fmt.Errorf("missing static solid section")
		}
		text = strings.Replace(text, solids, solids+generated.String(), 1)
	}
	formatted, err := sampleformat.YAML(context.Background(), []byte(text))
	if err != nil {
		return err
	}
	if check {
		if !bytes.Equal(original, formatted) {
			return fmt.Errorf("ceiling fixtures are stale; run mise run generate-hangar-ceiling-lights")
		}
		return nil
	}
	return os.WriteFile(root+"/world.yaml", formatted, 0o644)
}

func writeCeilingFixture(out *bytes.Buffer, id string, x, y, z, ceiling float64, broken bool) {
	// Keep the point source just below the diffuser, outside its shadow-casting
	// geometry. All pieces are visual trim above the player's walking space.
	writeCeilingBox(out, id, "housing", x-1.3, y-.16, x+1.3, y+.16, z+.10, z+.20, "hero-steel")
	if broken {
		// Two cracked, unpowered remnants and an exposed central channel make
		// this fixture read as damaged even when the torch illuminates it.
		writeCeilingBox(out, id, "diffuser-left", x-1.17, y-.105, x-.30, y+.105, z+.06, z+.10, "ceiling-strip-broken")
		writeCeilingBox(out, id, "diffuser-right", x+.24, y-.105, x+1.17, y+.105, z+.045, z+.10, "ceiling-strip-broken")
		writeCeilingBox(out, id, "exposed-channel", x-.30, y-.105, x+.24, y+.105, z+.10, z+.12, "ribbed")
	} else {
		writeCeilingBox(out, id, "diffuser", x-1.17, y-.105, x+1.17, y+.105, z+.06, z+.10, "ceiling-strip")
	}
	for index, offset := range []float64{-1.25, 1.25} {
		writeCeilingBox(out, id, fmt.Sprintf("end-%d", index), x+offset-.05, y-.18, x+offset+.05, y+.18, z+.045, z+.22, "steel")
	}
	for index, offset := range []float64{-.98, .98} {
		writeCeilingBox(
			out,
			id,
			fmt.Sprintf("hanger-%d", index),
			x+offset-.025,
			y-.025,
			x+offset+.025,
			y+.025,
			z+.20,
			ceiling-.03,
			"hero-steel",
		)
		writeCeilingBox(
			out,
			id,
			fmt.Sprintf("mount-%d", index),
			x+offset-.085,
			y-.085,
			x+offset+.085,
			y+.085,
			ceiling-.03,
			ceiling,
			"steel",
		)
	}
}

func writeCeilingBox(out *bytes.Buffer, fixture, part string, x0, y0, x1, y1, bottom, top float64, material string) {
	fmt.Fprintf(out, "  - id: ceiling-%s-%s\n", fixture, part)
	fmt.Fprintf(out, "    footprint: [{x: %g, y: %g}, {x: %g, y: %g}, {x: %g, y: %g}, {x: %g, y: %g}]\n", x0, y0, x1, y0, x1, y1, x0, y1)
	fmt.Fprintf(out, "    bottom: {c: %g}\n    top: {c: %g}\n", bottom, top)
	fmt.Fprintf(
		out,
		"    side_material: %s\n    top_material: %s\n    bottom_material: %s\n    collision: false\n",
		material,
		material,
		material,
	)
}
