//go:build ignore

// Generate original Vigil music and effects using only the Go standard library.
// Run from the CLI repository root with mise run generate-vigil-sounds.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"math"
	"os"
	"path/filepath"
)

const sampleRate = 24000
const soundDirectory = "samples/vigil/assets/sounds"
const tau = 2 * math.Pi

var errSound = errors.New("invalid or stale Vigil sound asset")

type soundSpec struct {
	name               string
	seconds, rms, peak float64
	loop               bool
	synth              func(int) []float64
}
type soundReport struct {
	Name         string  `json:"name"`
	Seconds      float64 `json:"seconds"`
	Samples      int     `json:"samples"`
	Peak         float64 `json:"peak"`
	RMS          float64 `json:"rms"`
	Mean         float64 `json:"mean"`
	Loop         bool    `json:"loop"`
	BoundaryStep float64 `json:"boundaryStep"`
	SHA256       string  `json:"sha256"`
}
type report struct {
	Version    int           `json:"version"`
	Generator  string        `json:"generator"`
	SampleRate int           `json:"sampleRate"`
	Channels   int           `json:"channels"`
	Bits       int           `json:"bits"`
	Sounds     []soundReport `json:"sounds"`
}

func main() {
	check := flag.Bool("check", false, "verify generated bytes, PCM bounds and loop/one-shot endpoints without writing")
	flag.Parse()
	if err := generate(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func generate(check bool) error {
	output := report{Version: 1, Generator: "scripts/vigil-sound-assets.go", SampleRate: sampleRate, Channels: 1, Bits: 16}
	for _, spec := range []soundSpec{
		{"church-ambience", 32, .030 * .35, .095 * .35, true, church},
		{"fireball-cast", .35, .090, .32, false, cast},
		{"fireball-impact", .65, .100, .36, false, impact},
		{"shrine-chime", 1.8, .065, .24, false, chime},
		{"stone-footstep", .18, .085, .32, false, footstep},
		{"ember-crackle", 3, .014, .085, true, crackle},
	} {
		samples := spec.synth(int(math.Round(spec.seconds * sampleRate)))
		normalize(samples, spec)
		data := wav(samples)
		decoded := pcmSamples(data)
		peak, rms, mean := statistics(decoded)
		boundary := math.Abs(decoded[0] - decoded[len(decoded)-1])
		if peak > spec.peak+1./32767 || math.Abs(mean) > .00002 {
			return fmt.Errorf("%w: %s peak/DC exceeds authored bound", errSound, spec.name)
		}
		if spec.loop {
			var largestStep float64
			for i := 1; i < len(decoded); i++ {
				largestStep = math.Max(largestStep, math.Abs(decoded[i]-decoded[i-1]))
			}
			if boundary > largestStep*1.1+1./32767 {
				return fmt.Errorf("%w: %s has discontinuous loop boundary", errSound, spec.name)
			}
		} else if decoded[0] != 0 || decoded[len(decoded)-1] != 0 {
			return fmt.Errorf("%w: %s one-shot endpoints are not silent", errSound, spec.name)
		}
		digest := sha256.Sum256(data)
		output.Sounds = append(
			output.Sounds,
			soundReport{
				spec.name + ".wav",
				spec.seconds,
				len(decoded),
				peak,
				rms,
				mean,
				spec.loop,
				boundary,
				hex.EncodeToString(digest[:]),
			},
		)
		if err := writeOrCheck(filepath.Join(soundDirectory, spec.name+".wav"), data, check); err != nil {
			return err
		}
		fmt.Printf("%s.wav: %.3fs, peak %.6f, RMS %.6f, loop=%t\n", spec.name, spec.seconds, peak, rms, spec.loop)
	}
	metadata, err := json.MarshalIndent(output, "", "  ")
	if err != nil {
		return err
	}
	return writeOrCheck(filepath.Join(soundDirectory, "sounds.generated.json"), append(metadata, '\n'), check)
}
func writeOrCheck(path string, data []byte, check bool) error {
	if check {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, data) {
			return fmt.Errorf("%w: %s; run mise run generate-vigil-sounds", errSound, path)
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0644)
}

// A slow four-chord organ bed. Frequencies and modulation complete integer
// cycles in 32 seconds; circular envelopes/delays preserve phase at the seam.
func church(count int) []float64 {
	samples := make([]float64, count)
	chords := [][4]int{{50, 57, 62, 65}, {46, 53, 57, 62}, {43, 50, 53, 58}, {45, 52, 55, 60}}
	for i := range samples {
		seconds := float64(i) / sampleRate
		for chord, notes := range chords {
			distance := math.Mod(seconds-(float64(chord)*8+4)+48, 32) - 16
			if math.Abs(distance) >= 8 {
				continue
			}
			envelope := .5 + .5*math.Cos(math.Pi*distance/8)
			for voice, note := range notes {
				frequency := math.Round(midi(note)*32) / 32
				phase := tau*frequency*seconds + float64(voice)*.71
				tone := math.Sin(phase) + .22*math.Sin(phase*2) + .07*math.Sin(phase*3) + .025*math.Sin(phase*4)
				breath := 1 + .012*math.Sin(tau*seconds/8+float64(voice))
				samples[i] += envelope * tone * breath * .14
			}
		}
		// Very quiet pedal joins the harmony without a prominent melodic line.
		samples[i] += .035 * math.Sin(tau*math.Round(midi(38)*32)/32*seconds)
	}
	return room(samples, true, []float64{.113, .227, .397, .631, .947}, []float64{.19, .14, .11, .075, .045})
}
func cast(count int) []float64 {
	samples := make([]float64, count)
	noise := newNoise(0x766967696c636173)
	var filtered, phase float64
	for i := range samples {
		progress := float64(i) / float64(count-1)
		filtered += .26 * (noise.next() - filtered)
		phase += tau * (180 + 430*progress*progress) / sampleRate
		envelope := math.Pow(math.Sin(math.Pi*progress), 1.8)
		samples[i] = envelope * (.72*filtered + .15*math.Sin(phase) + .035*math.Sin(phase*.5))
	}
	return room(samples, false, []float64{.043, .087}, []float64{.12, .07})
}
func impact(count int) []float64 {
	samples := make([]float64, count)
	noise := newNoise(0x766967696c686974)
	var filtered, phase float64
	for i := range samples {
		seconds := float64(i) / sampleRate
		filtered += .21 * (noise.next() - filtered)
		phase += tau * (45 + 90*math.Exp(-seconds*11)) / sampleRate
		attack := 1 - math.Exp(-seconds*450)
		samples[i] = attack * (.8*math.Sin(phase)*math.Exp(-seconds*12) + .56*filtered*math.Exp(-seconds*16) + .025*math.Sin(tau*1307*seconds)*math.Exp(-seconds*24))
	}
	return room(samples, false, []float64{.071, .139, .223}, []float64{.2, .11, .05})
}
func chime(count int) []float64 {
	samples := make([]float64, count)
	for _, note := range []struct{ start, frequency, gain float64 }{{0, midi(74), .7}, {.27, midi(81), .36}, {.59, midi(77), .30}} {
		for i := int(note.start * sampleRate); i < count; i++ {
			seconds := float64(i)/sampleRate - note.start
			attack := 1 - math.Exp(-seconds*160)
			fundamental := math.Sin(tau*note.frequency*seconds) * math.Exp(-seconds*2.5)
			upper := .22 * math.Sin(tau*note.frequency*2.003*seconds) * math.Exp(-seconds*4.5)
			halo := .055 * math.Sin(tau*note.frequency*3.011*seconds) * math.Exp(-seconds*6)
			samples[i] += note.gain * attack * (fundamental + upper + halo)
		}
	}
	return room(samples, false, []float64{.091, .183, .311}, []float64{.2, .12, .07})
}
func footstep(count int) []float64 {
	samples := make([]float64, count)
	noise := newNoise(0x766967696c737465)
	var filtered float64
	for i := range samples {
		seconds := float64(i) / sampleRate
		filtered += .28 * (noise.next() - filtered)
		attack := 1 - math.Exp(-seconds*950)
		heel := math.Sin(tau*108*seconds) * math.Exp(-seconds*48)
		grit := filtered * math.Exp(-seconds*38)
		toe := .19 * math.Sin(tau*170*seconds) * math.Exp(-math.Abs(seconds-.044)*80)
		samples[i] = attack * (.65*heel + .54*grit + toe)
	}
	return room(samples, false, []float64{.039}, []float64{.06})
}
func crackle(count int) []float64 {
	samples := make([]float64, count)
	noise := newNoise(0x766967696c656d62)
	raw := make([]float64, count)
	for i := range raw {
		raw[i] = noise.next()
	}
	// Warm the periodic low-pass state instead of crossfading an arbitrary seam.
	var filtered float64
	for pass := range 3 {
		for i, value := range raw {
			filtered += .04 * (value - filtered)
			if pass == 2 {
				samples[i] = filtered * .12
			}
		}
	}
	for range 27 {
		start := int((noise.next()+1)*.5*float64(count)) % count
		gain := .015 + .027*(noise.next()+1)*.5
		frequency := 420 + 760*(noise.next()+1)*.5
		length := int((.025 + .035*(noise.next()+1)*.5) * sampleRate)
		for j := range length {
			seconds := float64(j) / sampleRate
			envelope := (1 - math.Exp(-seconds*1600)) * math.Exp(-seconds*110)
			samples[(start+j)%count] += gain * envelope * (math.Sin(tau*frequency*seconds) + .45*noise.next())
		}
	}
	return room(samples, true, []float64{.047, .093}, []float64{.1, .06})
}
func room(source []float64, loop bool, delays, gains []float64) []float64 {
	samples := append([]float64(nil), source...)
	for tap, delay := range delays {
		offset := int(math.Round(delay * sampleRate))
		for i := range samples {
			index := i - offset
			if index < 0 {
				if !loop {
					continue
				}
				index += len(source)
			}
			samples[i] += source[index] * gains[tap]
		}
	}
	return samples
}
func normalize(samples []float64, spec soundSpec) {
	if !spec.loop {
		fade := math.Min(.07, spec.seconds*.18)
		for i := range samples {
			start := float64(i) / sampleRate
			end := float64(len(samples)-1-i) / sampleRate
			samples[i] *= math.Min(1, start/.003) * math.Min(1, end/fade)
		}
	}
	var total, weight float64
	for i, value := range samples {
		total += value
		weight += dcWindow(i, len(samples), spec.loop)
	}
	for i := range samples {
		samples[i] -= total / weight * dcWindow(i, len(samples), spec.loop)
	}
	peak, rms, _ := statistics(samples)
	gain := math.Min(spec.rms/rms, spec.peak/peak)
	for i := range samples {
		samples[i] *= gain
	}
}
func dcWindow(index, count int, loop bool) float64 {
	if loop {
		return 1
	}
	return math.Min(1, float64(index)/(sampleRate*.01)) * math.Min(1, float64(count-1-index)/(sampleRate*.01))
}
func statistics(samples []float64) (peak, rms, mean float64) {
	for _, value := range samples {
		peak = math.Max(peak, math.Abs(value))
		rms += value * value
		mean += value
	}
	return peak, math.Sqrt(rms / float64(len(samples))), mean / float64(len(samples))
}
func midi(note int) float64 { return 440 * math.Pow(2, float64(note-69)/12) }

type noiseSource struct{ state uint64 }

func newNoise(seed uint64) noiseSource { return noiseSource{seed} }
func (source *noiseSource) next() float64 {
	source.state ^= source.state << 13
	source.state ^= source.state >> 7
	source.state ^= source.state << 17
	return float64(source.state>>11)*(1./9007199254740992)*2 - 1
}
func wav(samples []float64) []byte {
	data := make([]byte, 44+len(samples)*2)
	copy(data, "RIFF")
	binary.LittleEndian.PutUint32(data[4:], uint32(len(data)-8))
	copy(data[8:], "WAVEfmt ")
	binary.LittleEndian.PutUint32(data[16:], 16)
	binary.LittleEndian.PutUint16(data[20:], 1)
	binary.LittleEndian.PutUint16(data[22:], 1)
	binary.LittleEndian.PutUint32(data[24:], sampleRate)
	binary.LittleEndian.PutUint32(data[28:], sampleRate*2)
	binary.LittleEndian.PutUint16(data[32:], 2)
	binary.LittleEndian.PutUint16(data[34:], 16)
	copy(data[36:], "data")
	binary.LittleEndian.PutUint32(data[40:], uint32(len(samples)*2))
	for i, value := range samples {
		binary.LittleEndian.PutUint16(data[44+i*2:], uint16(int16(math.Round(value*32767))))
	}
	return data
}
func pcmSamples(data []byte) []float64 {
	samples := make([]float64, (len(data)-44)/2)
	for i := range samples {
		samples[i] = float64(int16(binary.LittleEndian.Uint16(data[44+i*2:]))) / 32767
	}
	return samples
}
