func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	materials := []string{"stone", "tile", "wall", "ceiling", "ground", "wood", "metal"}
	images := map[string][]byte{}
	for _, name := range materials {
		var data bytes.Buffer
		if err := png.Encode(&data, texture(name)); err != nil {
			return err
		}
		images[name] = data.Bytes()
	}
	for _, preset := range []string{"daylight", "cartoon", "fantasy", "space"} {
		directory := filepath.Join("samples", "environment", "levels", preset)
		if err := os.MkdirAll(directory, 0o755); err != nil {
			return err
		}
		var manifest bytes.Buffer
		fmt.Fprintf(&manifest, "[level]\nname = \"levels.%s\"\nkind = \"world\"\n\n[world]\nsource = \"world.yaml\"\n", preset)
		for _, name := range materials {
			fmt.Fprintf(&manifest, "\n[[textures]]\nname = %q\nsource = %q\nprofile = \"environment\"\n", name, name+".png")
			preset := map[string]string{"stone": "stone", "tile": "concrete", "wall": "brick", "ceiling": "concrete", "ground": "foliage", "wood": "wood", "metal": "metal"}[name]
			metallic := 0.0
			if name == "metal" {
				metallic = .35
			}
			fmt.Fprintf(
				&manifest,
				"\n[textures.materialize]\npreset = %q\nmetallic_scale = %g\n\n[textures.material_strengths]\nnormal = 0.35\nheight = 0.05\nao = 0.5\nrim = 0.0\n",
				preset,
				metallic,
			)
			if err := os.WriteFile(filepath.Join(directory, name+".png"), images[name], 0o644); err != nil {
				return err
			}
		}
		if err := os.WriteFile(filepath.Join(directory, "level.toml"), manifest.Bytes(), 0o644); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(directory, "world.yaml"), worldYAML(preset), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func worldYAML(preset string) []byte {
	var data bytes.Buffer
	fmt.Fprintf(
		&data,
		"# $schema: ../../.karty/schemas/levels/%s.schema.json\n# Generated by scripts/environment-assets.go; edit that tracked generator.\nversion: 9\nenvironment:\n  preset: %s\n",
		preset,
		preset,
	)
	data.WriteString(
		"uv: {mode: triplanar, scale: {x: 2, y: 2}}\nlighting:\n  version: 1\n  actors: true\n  ambient: {x: 0.09, y: 0.10, z: 0.12}\n  lights:\n    - {id: observation-fill, position: {x: 0, y: -8, z: 3}, color: {x: 0.48, y: 0.41, z: 0.28}, radius: 11}\n    - {id: passage-fill, position: {x: 14, y: -3, z: 3}, color: {x: 0.3, y: 0.36, z: 0.38}, radius: 9}\nrooms:\n",
	)
	for _, r := range rooms {
		fmt.Fprintf(&data, "  - id: %s\n", r.id)
		if r.sky {
			data.WriteString("    sky: true\n")
		}
		fmt.Fprintf(
			&data,
			"    floor: {c: %g}\n    ceiling: {c: %g}\n    floor_material: %s\n    ceiling_material: ceiling\n    boundary:\n",
			r.floor,
			r.ceiling,
			r.floorMaterial,
		)
		for i, p := range r.points {
			q := r.points[(i+1)%len(r.points)]
			horizon := ""
			if (r.id == "test-ground" && i != 1) || (r.id == "courtyard" && (i == 6 || i == 8)) {
				horizon = ", sky: true"
			}
			fmt.Fprintf(
				&data,
				"      - {id: edge-%d, start: {x: %g, y: %g}, end: {x: %g, y: %g}, material: wall%s}\n",
				i,
				p.x,
				p.y,
				q.x,
				q.y,
				horizon,
			)
		}
	}
	data.WriteString("connections:\n")
	for i, l := range links {
		fmt.Fprintf(
			&data,
			"  - id: connection-%d\n    a: {room: %s, edge: edge-%d}\n    b: {room: %s, edge: edge-%d}\n",
			i,
			l.a,
			edge(l.a, l.start, l.end),
			l.b,
			edge(l.b, l.start, l.end),
		)
	}
	data.WriteString("solids:\n")
	// The crates make directional shadows legible. The north ground remains clear
	// so terrain and vegetation experiments can grow without rebuilding the entry.
	box(&data, "sun-test-crate", -4, 6, -1.5, 8.5, 0, 2.3, "wood")
	box(&data, "low-plinth", 3.5, 10, 7, 13, 0, .5, "stone")
	box(&data, "monolith", 4.5, 11, 6, 12, 0, 4, "metal")
	for _, p := range []point{{-9, 14}, {-9, 20}, {-3, 14}, {-3, 20}} {
		box(&data, fmt.Sprintf("canopy-post-%g-%g", p.x, p.y), p.x-.15, p.y-.15, p.x+.15, p.y+.15, 0, 3.3, "metal")
	}
	box(&data, "canopy-roof", -9.5, 13.5, -2.5, 20.5, 3.3, 3.6, "metal")
	box(&data, "west-bench", -11, 5, -9.5, 10, 0, .55, "stone")
	return data.Bytes()
}

func edge(id string, a, b point) int {
	for _, r := range rooms {
		if r.id == id {
			for i, p := range r.points {
				q := r.points[(i+1)%len(r.points)]
				if (p == a && q == b) || (p == b && q == a) {
					return i
				}
			}
		}
	}
	panic("missing authored portal edge: " + id)
}

func box(data *bytes.Buffer, id string, x0, y0, x1, y1, z0, z1 float64, material string) {
	fmt.Fprintf(
		data,
		"  - id: %s\n    footprint: [{x: %g, y: %g}, {x: %g, y: %g}, {x: %g, y: %g}, {x: %g, y: %g}]\n    bottom: {c: %g}\n    top: {c: %g}\n    side_material: %s\n    top_material: %s\n    bottom_material: %s\n    collision: true\n",
		id,
		x0,
		y0,
		x1,
		y0,
		x1,
		y1,
		x0,
		y1,
		z0,
		z1,
		material,
		material,
		material,
	)
}

func texture(name string) image.Image {
	const size = 128
	out := image.NewNRGBA(image.Rect(0, 0, size, size))
	base := map[string][3]int{"stone": {179, 178, 160}, "tile": {120, 133, 130}, "wall": {180, 185, 171}, "ceiling": {111, 122, 123}, "ground": {84, 113, 81}, "wood": {136, 95, 54}, "metal": {45, 75, 79}}[name]
	for y := 0; y < size; y++ {
		for x := 0; x < size; x++ {
			noise := ((x*17 + y*31 + (x*y)%37) % 11) - 5
			shade := noise
			switch name {
			case "stone", "tile":
				if x%64 < 2 || y%64 < 2 {
					shade -= 24
				}
				if x%64 == 3 || y%64 == 3 {
					shade += 12
				}
			case "wall":
				if y%32 < 2 || (x+(y/32%2)*32)%64 < 2 {
					shade -= 19
				}
			case "wood":
				shade += (x*3+y/4)%13 - 6
				if x%32 < 2 {
					shade -= 30
				}
				if y < 6 || y > 121 {
					shade -= 20
				}
			case "metal":
				if x < 3 || y < 3 || x > 124 || y > 124 {
					shade += 24
				}
				if (x == 12 || x == 116) && (y == 12 || y == 116) {
					shade += 50
				}
			case "ground":
				if x < 2 || y < 2 {
					shade += 7
				}
			}
			out.SetNRGBA(
				x,
				y,
				color.NRGBA{
					uint8(max(0, min(255, base[0]+shade))),
					uint8(max(0, min(255, base[1]+shade))),
					uint8(max(0, min(255, base[2]+shade))),
					255,
				},
			)
		}
	}
	return out
}
